defmodule Ssm.FakeScriptHost do
  @moduledoc """
  A fake host for the real `script.sh` under `sh` (as root in the test
  container) in container `/tmp` — outside the bind-mounted project, where
  real symlinks, hardlinks and chown work. `getent` reads the test's own
  `passwd`; `HOME` is the fake root's home. Same layout as
  `Ssm.Ssh.ScriptSafetyTest`.
  """

  alias Ssm.Ssh.ScriptRunner

  @head "# Auto-generated by Secure SSH Manager. DO NOT EDIT!"

  @doc "A fresh fake host: `%{dir, script, root_keys}`; removed on test exit."
  def setup! do
    dir = Path.join(System.tmp_dir!(), "ssm-host-#{System.unique_integer([:positive])}")
    File.mkdir_p!(Path.join(dir, "bin"))
    File.mkdir_p!(Path.join(dir, "root/.ssh"))
    ExUnit.Callbacks.on_exit(fn -> File.rm_rf!(dir) end)

    script = Path.join(dir, "script.sh")
    File.write!(script, ScriptRunner.script_source())

    fake_bin(%{dir: dir}, "getent", """
    if [ -n "$2" ]; then grep "^$2:" "#{dir}/passwd"; else cat "#{dir}/passwd"; fi\
    """)

    root_keys = Path.join(dir, "root/.ssh/authorized_keys")
    File.write!(root_keys, "#{@head}\nssh-ed25519 SSMKEY ssm\n")
    passwd_entry(%{dir: dir}, "root", 0, 0, Path.join(dir, "root"))

    %{dir: dir, script: script, root_keys: root_keys}
  end

  @doc "Append a passwd line (the home is not created)."
  def passwd_entry(%{dir: dir}, name, uid, gid, home) do
    File.write!(Path.join(dir, "passwd"), "#{name}:x:#{uid}:#{gid}::#{home}:/bin/sh\n", [
      :append
    ])

    home
  end

  @doc "A user with an existing home (no ~/.ssh) under `<dir>/home/<name>`."
  def add_user(ctx, name, uid \\ 1000, gid \\ 1000) do
    home = Path.join([ctx.dir, "home", name])
    File.mkdir_p!(home)
    passwd_entry(ctx, name, uid, gid, home)
  end

  @doc "An executable `<dir>/bin/<name>` (first in the script's PATH)."
  def fake_bin(%{dir: dir}, name, body) do
    path = Path.join([dir, "bin", name])
    File.write!(path, "#!/bin/sh\n" <> body <> "\n")
    File.chmod!(path, 0o755)
  end

  def env(%{dir: dir}) do
    [
      {"PATH", Path.join(dir, "bin") <> ":" <> System.get_env("PATH")},
      {"HOME", Path.join(dir, "root")},
      {"TMPDIR", dir}
    ]
  end

  @doc """
  `set_authorized_keyfile <args…>` with `content` on stdin: `{output,
  exit}`. A bare login writes as SSH user `root`.
  """
  def write(ctx, login, content) when is_binary(login), do: write(ctx, [login, "root"], content)

  def write(ctx, args, content) do
    input = Path.join(ctx.dir, "input")
    File.write!(input, content)

    System.cmd(
      "sh",
      ["-c", ~s(f="$1"; shift; sh "$0" set_authorized_keyfile "$@" < "$f"), ctx.script, input] ++
        List.wrap(args),
      env: env(ctx),
      stderr_to_stdout: true
    )
  end

  @doc "Any script command: `{output, exit}`."
  def run(ctx, args),
    do: System.cmd("sh", [ctx.script | args], env: env(ctx), stderr_to_stdout: true)
end
