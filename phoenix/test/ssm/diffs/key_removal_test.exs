defmodule Ssm.Diffs.KeyRemovalTest do
  @moduledoc """
  "Remove key" on the diff page: takes unauthorized (`extra_on_host`) lines
  out of one login's `authorized_keys` through `script.sh` — read fresh,
  only lines that are still extra, readonly and unsafe logins refused,
  ssm's own key never touched, every attempt audited.
  """

  use Ssm.DataCase, async: false

  import Ssm.Fixtures

  alias Ssm.Activity
  alias Ssm.Diffs.KeyRemoval
  alias Ssm.Ssh.{MockClient, Result}

  @version_probe "sh .ssm/script.sh version 2>/dev/null || true"
  @get_keyfiles "sh .ssm/script.sh get_ssh_keyfiles"
  @head "# Auto-generated by Secure SSH Manager. DO NOT EDIT!"
  @own Ssm.Test.OwnKeyStub.default()

  setup do
    start_supervised!(MockClient)
    :ok
  end

  defp stub_host(host, entries) do
    payload = Jason.encode!(%{version: "x", sha256: Ssm.Ssh.ScriptRunner.script_sha256()})
    MockClient.set_exec(host.id, @version_probe, %Result{stdout: payload})
    MockClient.set_exec(host.id, @get_keyfiles, %Result{stdout: Jason.encode!(entries)})
    MockClient.set_default_exec(%Result{exit_code: 0})
  end

  defp entry(login, lines, extra \\ %{}) do
    Map.merge(
      %{login: login, has_pragma: true, keyfile: Enum.join([@head | lines], "\n") <> "\n"},
      extra
    )
  end

  defp grant(host, login, base64) do
    user = user_fixture()
    key_fixture(user, %{key_type: "ssh-ed25519", key_base64: base64, name: "laptop"})
    authorization_fixture(user, host, %{login: login})
  end

  defp writes(host) do
    for {id, cmd, input} <- MockClient.calls().exec_inputs,
        id == host.id,
        [_, login] <- [Regex.run(~r/set_authorized_keyfile (\S+)/, cmd)],
        do: {login, input}
  end

  defp last_audit, do: hd(Activity.list())

  test "removes one unauthorized line, keeps every other line as it is" do
    host = host_fixture(%{name: "web1", username: "root"})
    grant(host, "deploy", "GRANTED")

    stub_host(host, [
      entry("deploy", [
        "ssh-ed25519 GRANTED laptop",
        "# a note typed by hand",
        "ssh-ed25519 ROGUE1 x",
        ~s(from="10.0.0.1" ssh-rsa ROGUE2 y)
      ])
    ])

    assert {:ok, %{removed: 1}} =
             KeyRemoval.remove(
               MockClient,
               host,
               "deploy",
               {:lines, ["ssh-ed25519 ROGUE1 x"]},
               "admin"
             )

    assert writes(host) == [
             {"deploy",
              "ssh-ed25519 GRANTED laptop\n# a note typed by hand\n" <>
                ~s(from="10.0.0.1" ssh-rsa ROGUE2 y\n)}
           ]

    audit = last_audit()
    assert {audit.activity_type, audit.action, audit.target} == {"host", "remove_keys", "web1"}
    assert audit.host_id == host.id
    assert audit.actor_username == "admin"
    assert Activity.details(audit)["login"] == "deploy"
    assert Activity.details(audit)["removed"] == 1
    refute inspect(Activity.details(audit)) =~ "ROGUE1"
  end

  test "remove all extra keys keeps granted keys and ssm's own key" do
    host = host_fixture(%{username: "root"})
    grant(host, "root", "GRANTED")

    stub_host(host, [
      entry("root", [@own <> " ssm", "ssh-ed25519 GRANTED laptop", "ssh-rsa ROGUE1 x", "junk"])
    ])

    assert {:ok, %{removed: 2}} = KeyRemoval.remove(MockClient, host, "root", :all_extra, "admin")
    assert writes(host) == [{"root", @own <> " ssm\nssh-ed25519 GRANTED laptop\n"}]
  end

  test "a line that is no longer unauthorized is not removed" do
    host = host_fixture()
    grant(host, "deploy", "NOWGRANTED")
    stub_host(host, [entry("deploy", ["ssh-ed25519 NOWGRANTED old-comment"])])

    assert {:error, {:stale, message}} =
             KeyRemoval.remove(
               MockClient,
               host,
               "deploy",
               {:lines, ["ssh-ed25519 NOWGRANTED old-comment"]},
               "admin"
             )

    assert message =~ "refresh"
    assert writes(host) == []
  end

  test "ssm's own key is never removed, even when asked for by line" do
    host = host_fixture(%{username: "root"})
    stub_host(host, [entry("root", [@own <> " ssm"])])

    assert {:error, {:stale, _}} =
             KeyRemoval.remove(MockClient, host, "root", {:lines, [@own <> " ssm"]}, "admin")

    assert writes(host) == []
  end

  test "refuses when ssm's own key is unavailable for the host's login user" do
    Application.put_env(:ssm, :test_own_public_key, :unavailable)
    on_exit(fn -> Application.delete_env(:ssm, :test_own_public_key) end)

    host = host_fixture(%{username: "root"})
    stub_host(host, [entry("root", [@own <> " ssm", "ssh-rsa ROGUE x"])])

    assert {:error, {:own_key_unavailable, _}} =
             KeyRemoval.remove(MockClient, host, "root", :all_extra, "admin")

    assert writes(host) == []
  end

  test "a disabled host is refused before any SSH and audited" do
    host = host_fixture(%{name: "off", disabled: true})

    assert {:error, {:host_disabled, _}} =
             KeyRemoval.remove(MockClient, host, "deploy", :all_extra, "admin")

    assert MockClient.calls().exec == []
    assert last_audit().action == "remove_keys_failed"
  end

  test "readonly and unsafe logins are refused, nothing written" do
    host = host_fixture()

    stub_host(host, [
      entry("frozen", ["ssh-rsa ROGUE x"], %{
        readonly_condition: "user_readonly (root-owned)",
        readonly_scope: "user"
      }),
      entry("host-ro", ["ssh-rsa ROGUE x"], %{
        readonly_condition: "Product is pfSense",
        readonly_scope: "platform"
      }),
      %{login: "linked", has_pragma: false, unsafe: "symlink", keyfile: ""},
      %{login: "dirlink", has_pragma: false, unsafe: "ssh_dir", keyfile: ""}
    ])

    for login <- ~w(frozen host-ro) do
      assert {:error, {:ssh_readonly, _}} =
               KeyRemoval.remove(MockClient, host, login, :all_extra, "admin")
    end

    for login <- ~w(linked dirlink) do
      assert {:error, {:ssh_unsafe, _}} =
               KeyRemoval.remove(MockClient, host, login, :all_extra, "admin")
    end

    assert writes(host) == []
    assert last_audit().action == "remove_keys_failed"
  end

  test "a login without a file on the host has nothing to remove" do
    host = host_fixture()
    stub_host(host, [])

    assert {:error, {:stale, _}} = KeyRemoval.remove(MockClient, host, "ghost", :all_extra, "a")
    assert writes(host) == []
  end

  test "a write the script refuses is reported and audited" do
    host = host_fixture(%{username: "root"})
    stub_host(host, [entry("toor", ["ssh-rsa ROGUE x"])])

    MockClient.set_exec(host.id, "sh .ssm/script.sh set_authorized_keyfile toor root", %Result{
      stdout: "Keyfile is unsafe (shared_home), aborting.",
      exit_code: 1
    })

    assert {:error, {:ssh_unsafe, _}} =
             KeyRemoval.remove(MockClient, host, "toor", :all_extra, "admin")

    assert last_audit().action == "remove_keys_failed"
    assert Activity.details(last_audit())["error"] =~ "shared_home"
  end

  test "a granted key's host line with other options is never removed" do
    host = host_fixture(%{username: "root"})
    user = user_fixture()
    key_fixture(user, %{key_type: "ssh-ed25519", key_base64: "OPTED", name: "laptop"})
    authorization_fixture(user, host, %{login: "deploy", options: "no-pty"})

    stub_host(host, [entry("deploy", ["ssh-ed25519 OPTED laptop", "ssh-rsa ROGUE x"])])

    assert {:ok, %{removed: 1}} =
             KeyRemoval.remove(MockClient, host, "deploy", :all_extra, "admin")

    assert writes(host) == [{"deploy", "ssh-ed25519 OPTED laptop\n"}]

    assert {:error, {:stale, _}} =
             KeyRemoval.remove(
               MockClient,
               host,
               "deploy",
               {:lines, ["ssh-ed25519 OPTED laptop"]},
               "admin"
             )
  end
end
