defmodule Ssm.Ssh.ScriptHardeningTest do
  @moduledoc """
  The real `script.sh` (as root in the test container, `Ssm.FakeScriptHost`):
  a `user_readonly` marker counts only inside a root-owned `~/.ssh` the user
  cannot write (else it is reported as tampered); renames are verified and
  refused without `mv -T`/`mv -h`; reads never follow a link swapped in after
  the checks; the listing writes no temp file.
  """

  use ExUnit.Case, async: true

  import Ssm.FakeScriptHost

  @head "# Auto-generated by Secure SSH Manager. DO NOT EDIT!"

  setup do
    setup!()
  end

  defp listing(ctx) do
    {out, 0} = run(ctx, ["get_ssh_keyfiles"])
    out |> Jason.decode!() |> Map.new(&{&1["login"], &1})
  end

  # the listing must finish: a read that follows a link to a FIFO would hang
  defp listing_within(ctx, ms) do
    task = Task.async(fn -> run(ctx, ["get_ssh_keyfiles"]) end)

    case Task.yield(task, ms) || Task.shutdown(task, :brutal_kill) do
      {:ok, {out, 0}} -> out |> Jason.decode!() |> Map.new(&{&1["login"], &1})
      other -> flunk("listing did not finish: #{inspect(other)}")
    end
  end

  defp user_ssh(ctx, name, uid \\ 1000) do
    home = add_user(ctx, name, uid, uid)
    ssh = Path.join(home, ".ssh")
    File.mkdir_p!(ssh)
    ssh
  end

  describe "user_readonly (M3)" do
    test "ssm's own file moved to user_readonly in a user-owned ~/.ssh is tampered, not honoured",
         ctx do
      ssh = user_ssh(ctx, "mover")
      {_, 0} = System.cmd("chown", ["1000:1000", ssh])
      File.chmod!(ssh, 0o700)
      assert {_, 0} = write(ctx, "mover", "ssh-ed25519 OLD x\n")
      keys = Path.join(ssh, "authorized_keys")
      assert File.lstat!(keys).uid == 0
      # what the login's user can do in their own ~/.ssh
      File.rename!(keys, Path.join(ssh, "user_readonly"))
      File.write!(keys, "ssh-ed25519 OLD x\n")

      entry = listing(ctx)["mover"]
      assert entry["readonly_condition"] == ""
      assert entry["readonly_scope"] == ""
      assert entry["readonly_ignored"] =~ "tampered"

      assert {_, 0} = write(ctx, "mover", "ssh-ed25519 NEW y\n")
      assert File.read!(keys) =~ "ssh-ed25519 NEW y"
    end

    test "a root-owned marker in a group- or world-writable ~/.ssh is tampered", ctx do
      for {name, mode} <- [{"gw", 0o770}, {"ow", 0o757}] do
        ssh = user_ssh(ctx, name)
        File.chmod!(ssh, mode)
        File.write!(Path.join(ssh, "authorized_keys"), "ssh-ed25519 K x\n")
        File.write!(Path.join(ssh, "user_readonly"), "frozen\n")

        entry = listing(ctx)[name]
        assert entry["readonly_condition"] == "", name
        assert entry["readonly_ignored"] =~ "tampered", name
        assert {_, 0} = write(ctx, name, "ssh-ed25519 NEW y\n")
      end
    end

    test "a marker that is an ssm-written keyfile is tampered even in a root-owned ~/.ssh", ctx do
      ssh = user_ssh(ctx, "copied")
      File.write!(Path.join(ssh, "authorized_keys"), "ssh-ed25519 K x\n")
      File.write!(Path.join(ssh, "user_readonly"), "#{@head}\nssh-ed25519 K x\n")

      entry = listing(ctx)["copied"]
      assert entry["readonly_condition"] == ""
      assert entry["readonly_ignored"] =~ "tampered"
    end

    test "a plain root-owned marker in a root-owned 0755 ~/.ssh is still honoured", ctx do
      ssh = user_ssh(ctx, "frozen")
      File.chmod!(ssh, 0o755)
      File.write!(Path.join(ssh, "authorized_keys"), "ssh-ed25519 K x\n")
      File.write!(Path.join(ssh, "user_readonly"), "staff froze this\n")

      entry = listing(ctx)["frozen"]
      assert entry["readonly_condition"] == "user_readonly (root-owned)"
      assert entry["readonly_ignored"] == ""
      assert {out, 1} = write(ctx, "frozen", "ssh-ed25519 NEW y\n")
      assert out =~ "readonly"
    end
  end

  describe "renames (L8)" do
    test "without mv -T and mv -h the write is refused with a clear reason", ctx do
      fake_bin(
        ctx,
        "mv",
        ~s(case "$*" in *-T*|*-h*\) echo "mv: invalid option" >&2; exit 1 ;; esac
        exec /bin/mv "$@")
      )

      ssh = user_ssh(ctx, "oldbbx")
      keys = Path.join(ssh, "authorized_keys")
      File.write!(keys, "#{@head}\nssh-ed25519 OLD x\n")

      assert {out, 1} = write(ctx, "oldbbx", "ssh-ed25519 NEW y\n")
      assert out =~ "Keyfile is unsafe (no_safe_rename)"
      assert File.read!(keys) == "#{@head}\nssh-ed25519 OLD x\n"
      assert Path.wildcard(Path.join(ssh, ".authorized_keys.ssm.*")) == []
    end

    test "an entry that is not ssm's renamed file after the mv is refused (race)", ctx do
      user_ssh(ctx, "swapper")
      other = Path.join(ctx.dir, "other")
      File.write!(other, "x\n")

      # the rename happens, then the user swaps the entry for a link
      fake_bin(ctx, "mv", ~s(/bin/mv "$@" || exit 1
      for last; do :; done
      case "$last" in authorized_keys\) rm -f "$last"; ln -s "#{other}" "$last" ;; esac))

      assert {out, 1} = write(ctx, "swapper", "ssh-ed25519 NEW y\n")
      assert out =~ "Keyfile is unsafe (race)"
    end
  end

  describe "reads (L9)" do
    # bounded/timeout wraps every read: swap the entry for a link right before
    setup ctx do
      ssh = user_ssh(ctx, "swapread")
      keys = Path.join(ssh, "authorized_keys")
      File.write!(keys, "ssh-ed25519 K x\n")
      %{keys: keys}
    end

    # reported unsafe (the failed read, or the link seen afterwards), never shown
    defp assert_not_read(entry) do
      assert entry["keyfile"] == ""
      assert entry["unsafe"] in ["race", "symlink"]
    end

    defp swap_before_read(ctx, target) do
      fake_bin(ctx, "timeout", ~s(shift
      case "$*" in *"#{ctx.keys}"*\) rm -f "#{ctx.keys}"; ln -s "#{target}" "#{ctx.keys}" ;; esac
      exec "$@"))
    end

    test "a link to a FIFO swapped in before the read is never opened", ctx do
      fifo = Path.join(ctx.dir, "fifo")
      {_, 0} = System.cmd("mkfifo", [fifo])
      swap_before_read(ctx, fifo)

      assert_not_read(listing_within(ctx, 15_000)["swapread"])
    end

    test "a link to a secret swapped in before the read is not shown (with perl)", ctx do
      secret = Path.join(ctx.dir, "secret")
      File.write!(secret, "root:SECRETHASH:19000:0:99999:7:::\n")
      swap_before_read(ctx, secret)

      entries = listing(ctx)
      assert_not_read(entries["swapread"])
      refute inspect(entries) =~ "SECRETHASH"
    end

    test "without perl the /proc check still refuses a swapped link", ctx do
      fake_bin(ctx, "perl", "exit 127")
      secret = Path.join(ctx.dir, "secret")
      File.write!(secret, "root:SECRETHASH:19000:0:99999:7:::\n")
      swap_before_read(ctx, secret)

      entries = listing(ctx)
      assert_not_read(entries["swapread"])
      refute inspect(entries) =~ "SECRETHASH"
    end

    test "a plain file is read through the nofollow path", ctx do
      assert %{"unsafe" => "", "keyfile" => "ssh-ed25519 K x"} = listing(ctx)["swapread"]
    end
  end

  describe "listing temp file (L10)" do
    test "the listing needs no writable TMPDIR and leaves nothing there", ctx do
      File.write!(Path.join(user_ssh(ctx, "tmpless"), "authorized_keys"), "k\n")
      env = env(ctx) ++ [{"TMPDIR", Path.join(ctx.dir, "missing")}]

      # no error output either: nothing is written under TMPDIR
      {out, 0} =
        System.cmd("sh", [ctx.script, "get_ssh_keyfiles"], env: env, stderr_to_stdout: true)

      assert out |> Jason.decode!() |> Enum.map(& &1["login"]) |> Enum.member?("tmpless")
      assert Path.wildcard(Path.join(ctx.dir, "homedirs.*")) == []
    end
  end

  describe "logins that look like options (L7)" do
    test "a login starting with - never reaches getent as an argument", ctx do
      log = Path.join(ctx.dir, "getent.log")

      fake_bin(ctx, "getent", """
      echo "$*" >> "#{log}"
      if [ -n "$2" ]; then grep "^$2:" "#{ctx.dir}/passwd"; else cat "#{ctx.dir}/passwd"; fi\
      """)

      for login <- ["-s", "--service=files", "-"] do
        assert {out, 1} = write(ctx, login, "ssh-ed25519 K x\n")
        assert out =~ "unsafe (home)", login
        assert {"unknown\n", 1} = run(ctx, ["has_keyfile", login])
      end

      calls = if File.exists?(log), do: File.read!(log), else: ""
      refute calls =~ ~r/(^|\s)-/m
    end
  end
end
