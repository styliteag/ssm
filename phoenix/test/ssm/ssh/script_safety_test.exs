defmodule Ssm.Ssh.ScriptSafetyTest do
  @moduledoc """
  The real `script.sh` under `sh` (as root in the test container) against a
  fake host in container `/tmp` — outside the bind-mounted project, where
  real symlinks, hardlinks and chown work. ssm runs the script as root: a
  user must never make it read or write another file through a link.
  """

  use ExUnit.Case, async: true

  alias Ssm.Ssh.ScriptRunner

  @uid 1000

  setup do
    dir = Path.join(System.tmp_dir!(), "ssm-safety-#{System.unique_integer([:positive])}")
    File.mkdir_p!(Path.join(dir, "bin"))
    File.mkdir_p!(Path.join(dir, "root/.ssh"))
    on_exit(fn -> File.rm_rf!(dir) end)

    script = Path.join(dir, "script.sh")
    File.write!(script, ScriptRunner.script_source())

    File.write!(Path.join(dir, "bin/getent"), """
    #!/bin/sh
    if [ -n "$2" ]; then grep "^$2:" "#{dir}/passwd"; else cat "#{dir}/passwd"; fi
    """)

    File.chmod!(Path.join(dir, "bin/getent"), 0o755)
    # the SSH user every write names (set_authorized_keyfile <login> root)
    File.write!(Path.join(dir, "passwd"), "root:x:0:0::#{Path.join(dir, "root")}:/bin/sh\n")

    # root's own file, as onboarding leaves it: ssm's header plus its key
    root_keys = Path.join(dir, "root/.ssh/authorized_keys")

    File.write!(
      root_keys,
      "# Auto-generated by Secure SSH Manager. DO NOT EDIT!\nssh-ed25519 SSMKEY ssm\n"
    )

    %{dir: dir, script: script, root_keys: root_keys}
  end

  defp add_user(%{dir: dir}, name) do
    home = Path.join([dir, "home", name])
    File.mkdir_p!(home)

    File.write!(Path.join(dir, "passwd"), "#{name}:x:#{@uid}:#{@uid}::#{home}:/bin/sh\n", [
      :append
    ])

    home
  end

  defp ssh_dir(home) do
    dir = Path.join(home, ".ssh")
    File.mkdir_p!(dir)
    dir
  end

  defp env(%{dir: dir}) do
    [
      {"PATH", Path.join(dir, "bin") <> ":" <> System.get_env("PATH")},
      {"HOME", Path.join(dir, "root")},
      {"TMPDIR", dir}
    ]
  end

  defp listing(ctx) do
    {out, 0} = System.cmd("sh", [ctx.script, "get_ssh_keyfiles"], env: env(ctx))
    out |> Jason.decode!() |> Map.new(&{&1["login"], &1})
  end

  defp write(ctx, login, content) do
    input = Path.join(ctx.dir, "input")
    File.write!(input, content)

    System.cmd(
      "sh",
      ["-c", ~s(sh "$0" set_authorized_keyfile "$1" root < "$2"), ctx.script, login, input],
      env: env(ctx),
      stderr_to_stdout: true
    )
  end

  defp stat!(path), do: File.lstat!(path)

  describe "write side" do
    test "a symlinked authorized_keys is replaced, never written through", ctx do
      home = add_user(ctx, "evil")
      keys = Path.join(ssh_dir(home), "authorized_keys")
      File.ln_s!(ctx.root_keys, keys)
      before = File.read!(ctx.root_keys)

      assert {_, 0} = write(ctx, "evil", "ssh-ed25519 GRANTED x\n")
      assert File.read!(ctx.root_keys) == before
      assert stat!(keys).type == :regular
      assert File.read!(keys) =~ "ssh-ed25519 GRANTED x"
    end

    test "a hardlinked authorized_keys is replaced, root's file keeps its content", ctx do
      home = add_user(ctx, "evil3")
      keys = Path.join(ssh_dir(home), "authorized_keys")
      File.ln!(ctx.root_keys, keys)
      before = File.read!(ctx.root_keys)

      assert {_, 0} = write(ctx, "evil3", "ssh-ed25519 GRANTED x\n")
      assert File.read!(ctx.root_keys) == before
      assert stat!(ctx.root_keys).links == 1
      assert File.read!(keys) =~ "ssh-ed25519 GRANTED x"
    end

    test "a symlinked ~/.ssh is refused", ctx do
      home = add_user(ctx, "evil2")
      File.ln_s!(Path.join(ctx.dir, "root/.ssh"), Path.join(home, ".ssh"))
      before = File.read!(ctx.root_keys)

      assert {out, 1} = write(ctx, "evil2", "ssh-ed25519 ATTACKER x\n")
      assert out =~ "unsafe (ssh_dir)"
      assert File.read!(ctx.root_keys) == before
    end

    test "authorized_keys.backup as a symlink to a directory: nothing lands there", ctx do
      ssh = ssh_dir(add_user(ctx, "cron"))
      cron = Path.join(ctx.dir, "cron.hourly")
      File.mkdir_p!(cron)
      File.ln_s!(cron, Path.join(ssh, "authorized_keys.backup"))
      File.write!(Path.join(ssh, "authorized_keys"), "#!/bin/sh\ntouch /pwned\n")
      File.chmod!(Path.join(ssh, "authorized_keys"), 0o755)

      assert {_, 0} = write(ctx, "cron", "ssh-rsa NEW y\n")
      assert File.ls!(cron) == []
      assert [backup] = Path.wildcard(Path.join(ssh, "authorized_keys.backup.*"))
      assert File.read!(backup) == "#!/bin/sh\ntouch /pwned\n"
    end

    test "authorized_keys as a symlink to a directory: the entry is replaced, the dir untouched",
         ctx do
      ssh = ssh_dir(add_user(ctx, "dirlink"))
      target = Path.join(ctx.dir, "sudoers.d")
      File.mkdir_p!(target)
      File.ln_s!(target, Path.join(ssh, "authorized_keys"))

      assert {_, 0} = write(ctx, "dirlink", "ssh-rsa NEW y\n")
      assert File.ls!(target) == []
      assert stat!(Path.join(ssh, "authorized_keys")).type == :regular
    end

    test "a normal write replaces the file atomically: root-owned 0644, as before", ctx do
      home = add_user(ctx, "alice")
      keys = Path.join(ssh_dir(home), "authorized_keys")
      File.write!(keys, "# Auto-generated by Secure SSH Manager. DO NOT EDIT!\nssh-rsa OLD x\n")
      old_inode = stat!(keys).inode

      assert {_, 0} = write(ctx, "alice", "ssh-rsa NEW y\n")

      assert File.read!(keys) ==
               "# Auto-generated by Secure SSH Manager. DO NOT EDIT!\nssh-rsa NEW y\n"

      stat = stat!(keys)
      assert stat.type == :regular
      assert stat.inode != old_inode
      assert stat.uid == 0
      assert Bitwise.band(stat.mode, 0o777) == 0o644
      assert Path.wildcard(Path.join(Path.dirname(keys), ".authorized_keys.ssm.*")) == []
      assert Path.wildcard(Path.join(Path.dirname(keys), "authorized_keys.backup*")) == []
    end

    test "a handwritten file is backed up under a fresh name first", ctx do
      home = add_user(ctx, "bob")
      keys = Path.join(ssh_dir(home), "authorized_keys")
      File.write!(keys, "ssh-rsa HANDMADE x\n")

      assert {_, 0} = write(ctx, "bob", "ssh-rsa NEW y\n")
      assert [backup] = Path.wildcard(keys <> ".backup.*")
      assert File.read!(backup) == "ssh-rsa HANDMADE x\n"
    end
  end

  describe "read side" do
    test "a symlinked or hardlinked authorized_keys is reported unsafe, its content never shown",
         ctx do
      secret = Path.join(ctx.dir, "secret")
      File.write!(secret, "root:SECRETHASH:19000:0:99999:7:::\n")

      File.ln_s!(secret, Path.join(ssh_dir(add_user(ctx, "sym")), "authorized_keys"))
      File.ln!(secret, Path.join(ssh_dir(add_user(ctx, "hard")), "authorized_keys"))

      entries = listing(ctx)

      assert %{"unsafe" => "symlink", "keyfile" => ""} = entries["sym"]
      assert %{"unsafe" => "hardlink", "keyfile" => ""} = entries["hard"]
      refute inspect(entries) =~ "SECRETHASH"
    end

    test "a symlinked ~/.ssh is reported unsafe", ctx do
      home = add_user(ctx, "symdir")
      other = Path.join(ctx.dir, "elsewhere/.ssh")
      File.mkdir_p!(other)
      File.write!(Path.join(other, "authorized_keys"), "ssh-rsa ELSEWHERE x\n")
      File.ln_s!(other, Path.join(home, ".ssh"))

      assert %{"unsafe" => "ssh_dir", "keyfile" => ""} = listing(ctx)["symdir"]
    end

    test "~/.ssh symlinked to root's ~/.ssh (lab case) is listed as unsafe ssh_dir", ctx do
      home = add_user(ctx, "labtest")
      File.ln_s!(Path.join(ctx.dir, "root/.ssh"), Path.join(home, ".ssh"))

      assert %{"unsafe" => "ssh_dir", "keyfile" => ""} = listing(ctx)["labtest"]
    end

    test "a FIFO is reported special and never opened (the listing does not hang)", ctx do
      ssh = ssh_dir(add_user(ctx, "fifo"))
      {_, 0} = System.cmd("mkfifo", [Path.join(ssh, "authorized_keys")])

      assert %{"unsafe" => "special", "keyfile" => ""} = listing(ctx)["fifo"]
    end

    test "a plain file is read and not unsafe", ctx do
      keys = Path.join(ssh_dir(add_user(ctx, "plain")), "authorized_keys")
      File.write!(keys, "ssh-rsa PLAIN x\n")

      assert %{"unsafe" => "", "keyfile" => "ssh-rsa PLAIN x"} = listing(ctx)["plain"]
    end
  end

  describe "failures inside the script" do
    defp fake_bin(ctx, name, body) do
      path = Path.join([ctx.dir, "bin", name])
      File.write!(path, "#!/bin/sh\n" <> body <> "\n")
      File.chmod!(path, 0o755)
    end

    test "a read that fails (race, timeout) reports the login as unsafe: race and goes on",
         ctx do
      for name <- ["one", "two"] do
        File.write!(Path.join(ssh_dir(add_user(ctx, name)), "authorized_keys"), "ssh-rsa K x\n")
      end

      # every bounded read fails, as a timeout or a detected swap would
      fake_bin(ctx, "timeout", "exit 124")

      entries = listing(ctx)
      assert %{"unsafe" => "race", "keyfile" => ""} = entries["one"]
      assert %{"unsafe" => "race", "keyfile" => ""} = entries["two"]
    end

    # busybox: neither mv -T nor mv -h
    defp busybox_mv(ctx) do
      fake_bin(
        ctx,
        "mv",
        ~s(case "$*" in *-T*|*-h*\) echo "mv: invalid option" >&2; exit 1 ;; esac
      exec /bin/mv "$@")
      )
    end

    test "without mv -T/-h a symlink-to-dir authorized_keys is removed and replaced", ctx do
      busybox_mv(ctx)
      ssh = ssh_dir(add_user(ctx, "bbx"))
      target = Path.join(ctx.dir, "sudoers.d")
      File.mkdir_p!(target)
      File.ln_s!(target, Path.join(ssh, "authorized_keys"))

      assert {_, 0} = write(ctx, "bbx", "ssh-rsa NEW y\n")
      assert File.ls!(target) == []
      assert stat!(Path.join(ssh, "authorized_keys")).type == :regular
      assert File.read!(Path.join(ssh, "authorized_keys")) =~ "ssh-rsa NEW y"
    end

    test "a real directory named authorized_keys is refused as unsafe (link-to-dir)", ctx do
      busybox_mv(ctx)
      ssh = ssh_dir(add_user(ctx, "dirk"))
      File.mkdir_p!(Path.join(ssh, "authorized_keys"))

      assert {out, 1} = write(ctx, "dirk", "ssh-rsa NEW y\n")
      assert out =~ "Keyfile is unsafe (link-to-dir)"
      assert File.ls!(Path.join(ssh, "authorized_keys")) == []
      assert Path.wildcard(Path.join(ssh, ".authorized_keys.ssm.*")) == []
    end

    test "the write aborts when od yields no 16 hex digits (no predictable names)", ctx do
      home = add_user(ctx, "carol")
      keys = Path.join(ssh_dir(home), "authorized_keys")
      File.write!(keys, "ssh-rsa HANDMADE x\n")

      for body <- ["exit 1", "echo ' 00 11'"] do
        fake_bin(ctx, "od", body)
        assert {out, 1} = write(ctx, "carol", "ssh-rsa NEW y\n")
        assert out =~ "random"
        assert File.read!(keys) == "ssh-rsa HANDMADE x\n"
        assert File.ls!(Path.dirname(keys)) == ["authorized_keys"]
      end
    end
  end

  describe "user_readonly" do
    test "a hardlinked root-owned marker is ignored and its content never shown", ctx do
      secret = Path.join(ctx.dir, "secret")
      File.write!(secret, "root:SECRETHASH:19000:0:99999:7:::\n")
      ssh = ssh_dir(add_user(ctx, "leak"))
      File.write!(Path.join(ssh, "authorized_keys"), "ssh-rsa L x\n")
      File.ln!(secret, Path.join(ssh, "user_readonly"))

      entry = listing(ctx)["leak"]
      assert entry["readonly_condition"] == ""
      assert entry["readonly_ignored"] =~ "link"
      refute inspect(entry) =~ "SECRETHASH"
    end

    test "a plain root-owned marker freezes the login with a fixed reason, not its content",
         ctx do
      ssh = ssh_dir(add_user(ctx, "frozen"))
      File.write!(Path.join(ssh, "authorized_keys"), "ssh-rsa F x\n")
      File.write!(Path.join(ssh, "user_readonly"), "private text\n")

      entry = listing(ctx)["frozen"]
      assert entry["readonly_condition"] == "user_readonly (root-owned)"
      assert entry["readonly_scope"] == "user"
      refute inspect(entry) =~ "private text"
    end
  end
end
