#!/usr/bin/env sh

set -eu

# shellcheck disable=SC3040
(set -o pipefail 2> /dev/null) && set -o pipefail

authorized_keys_location=".ssh/authorized_keys"
version="Secure SSH Manager script v0.3-alpha"
keyfile_head="# Auto-generated by Secure SSH Manager. DO NOT EDIT!"

have_getent() {
  command -v getent >/dev/null 2>&1
}

do_getent_passwd_all() {
  if have_getent; then
    getent passwd
  else
    cat /etc/passwd
  fi
}

# Without getent (busybox) the login must match field 1 exactly: a regex
# would let "roo." match root. ENVIRON, not awk -v (no escape processing).
do_getent_passwd() {
  login="$1"
  if have_getent; then
    getent passwd "${login}"
  else
    ssm_login="${login}" awk -F: \
      'BEGIN { r = 2 } $1 == ENVIRON["ssm_login"] { print; r = 0; exit } END { exit r }' /etc/passwd
  fi
}

# TODO: Read authorized_keys location from sshd config
# Get the location of the authorized keyfile given a login
get_authorized_keys_location() {
  login="$1"
  home=$(do_getent_passwd "${login}" | cut -d: -f6)
  
  echo "${home}/${authorized_keys_location}"
}

# Check if the system has any condition that make the keyfile externally
# managed or readonly. Returns only the first met condition
check_keyfile_condition() {
    login="$1"

    # Check for global override
    system_readonly="${HOME}/.ssh/system_readonly"
    if [ -f "${system_readonly}" ]; then
        content=$(cat "${system_readonly}")
        if [ -n "${content}" ]; then
            printf "%s" "${content}"
        else
            printf "Global overrride '%s' exists" "${system_readonly}"
        fi
        return 0
    fi
    
    # Check for specific systems (host-wide, before any per-login marker)
    platform=$(platform_condition)
    if [ -n "${platform}" ]; then
        printf "%s" "${platform}"
        return 0
    fi

    # Check for user override (only a plain root-owned marker counts). Its
    # content is never shown: a marker could be a link to any file.
    if [ "$(user_readonly_state "${login}")" = "root" ]; then
        printf "user_readonly (root-owned)"
        return 0
    fi
}

# Path of a login's user_readonly marker.
user_readonly_file() {
    home=$(do_getent_passwd "$1" | cut -d: -f6)
    printf "%s" "${home}/.ssh/user_readonly"
}

# State of a login's user_readonly: "root" (a plain file owned by uid 0 with
# one link, in a ~/.ssh that is no link: honoured), "link" (a symlink or
# hardlink, or ~/.ssh is unsafe: ignored), "other" (owned by someone else:
# ignored, the login's user could freeze their own revocation), "tampered"
# (root-owned, but in a ~/.ssh that root does not own or that group/other
# can write — the user could have renamed any root-owned file there, such
# as ssm's own authorized_keys, to user_readonly — or the marker is an
# ssm-written keyfile: ignored and reported) or "" (none).
# find -user/-links/-type/-perm are POSIX (GNU, busybox, BSD), unlike stat.
user_readonly_state() {
    marker=$(user_readonly_file "$1")
    if [ ! -e "${marker}" ] && [ ! -h "${marker}" ]; then
        return 0
    fi
    if [ -h "${marker}" ] || [ -n "$(ssh_dir_unsafe "$1")" ] \
        || [ -z "$(find "${marker}" -prune -type f -links 1 2>/dev/null)" ]; then
        echo "link"
    elif [ -z "$(find "${marker}" -prune -user 0 2>/dev/null)" ]; then
        echo "other"
    elif [ -z "$(find "${marker%/*}" -prune -user 0 ! -perm -020 ! -perm -002 2>/dev/null)" ]; then
        echo "tampered"
    # only now read (plain, root-owned, in a directory only root can change)
    elif [ "$(bounded head -n 1 "${marker}" 2>/dev/null)" = "${keyfile_head}" ]; then
        echo "tampered"
    else
        echo "root"
    fi
}

# Home dir of a login (getent passwd field 6).
login_home() {
    do_getent_passwd "$1" | cut -d: -f6
}

# Home of a login with every symlink resolved (pwd -P), else the getent
# field as it is; "" for an unknown login.
resolved_home() {
    home=$(login_home "$1") || return 0
    [ -n "${home}" ] || return 0
    (cd "${home}" 2>/dev/null && pwd -P) || printf "%s\n" "${home}"
}

# "ssh_dir" when the login's ~/.ssh is a symlink or does not resolve to the
# .ssh directory inside its (resolved) home, else "". A home that is itself
# reached through a symlink (FreeBSD /home -> /usr/home) is fine.
ssh_dir_unsafe() {
    home=$(login_home "$1")
    dir="${home}/.ssh"
    if [ -h "${dir}" ]; then
        echo "ssh_dir"
        return 0
    fi
    if [ -d "${dir}" ]; then
        real_home=$(cd "${home}" 2>/dev/null && pwd -P) || real_home=""
        real_dir=$(cd "${dir}" 2>/dev/null && pwd -P) || real_dir=""
        if [ -z "${real_home}" ] || [ "${real_dir}" != "${real_home}/.ssh" ]; then
            echo "ssh_dir"
        fi
    fi
}

# Why ssm (running as root) must not read a login's authorized_keys:
# "ssh_dir" (~/.ssh is a link: not written either), "symlink", "hardlink"
# (more than one link) or "special" (not a regular file) — these three are
# replaced by a write, never written through — or "" (safe).
keyfile_unsafe() {
    dir_state=$(ssh_dir_unsafe "$1")
    if [ -n "${dir_state}" ]; then
        echo "${dir_state}"
        return 0
    fi
    file="$(login_home "$1")/${authorized_keys_location}"
    if [ -h "${file}" ]; then
        echo "symlink"
    elif [ ! -e "${file}" ]; then
        return 0
    elif [ ! -f "${file}" ]; then
        echo "special"
    elif [ -n "$(find "${file}" -prune -links +1 2>/dev/null)" ]; then
        echo "hardlink"
    fi
}

# Run "$@" with a time limit where timeout(1) exists (a FIFO swapped in
# must not hang the script).
bounded() {
    if command -v timeout >/dev/null 2>&1; then
        timeout 10 "$@"
    else
        "$@"
    fi
}

# sha256 (hex) of stdin; "" without sha256sum (no check then).
content_sha() {
    if command -v sha256sum >/dev/null 2>&1; then
        sha256sum | awk '{ print $1 }'
    else
        cat >/dev/null
    fi
}

# True when perl can open with O_NOFOLLOW|O_NONBLOCK (Fcntl).
have_nofollow_perl() {
    command -v perl >/dev/null 2>&1 \
        && perl -MFcntl=O_RDONLY,O_NOFOLLOW,O_NONBLOCK -e 1 >/dev/null 2>&1
}

# Print a plain authorized_keys. With perl, the file is opened with
# O_NOFOLLOW|O_NONBLOCK (a link swapped in after the checks is never
# followed, nothing behind it is opened, a FIFO cannot block) and the
# opened file must be a regular file with one link and the very inode of the
# directory entry. Without perl on Linux the opened file is checked the same
# way through /proc/<pid>/fd (the open itself follows a link). Elsewhere the
# entry is checked before and after the read (same inode, plain, one link):
# a link swapped in and back in between is not seen (documented limitation).
read_keyfile() {
    if have_nofollow_perl; then
        # shellcheck disable=SC2016
        bounded perl -MFcntl=O_RDONLY,O_NOFOLLOW,O_NONBLOCK -e '
            my $p = shift;
            sysopen(my $fh, $p, O_RDONLY | O_NOFOLLOW | O_NONBLOCK) or exit 1;
            my @f = stat($fh) or exit 1;
            -f _ or exit 1;
            $f[3] == 1 or exit 1;
            my @l = lstat($p) or exit 1;
            ($f[0] == $l[0] && $f[1] == $l[1]) or exit 1;
            binmode($fh);
            binmode(STDOUT);
            local $/;
            my $c = <$fh>;
            defined($c) or $c = "";
            print $c or exit 1;
            exit 0;' "$1"
    elif [ -d /proc/self/fd ]; then
        # shellcheck disable=SC2016
        bounded sh -c '
            exec 3< "$1" || exit 1
            opened=$(ls -iL "/proc/$$/fd/3" | awk "{ print \$1 }")
            entry=$(ls -id "$1" | awk "{ print \$1 }")
            [ "${opened}" = "${entry}" ] || exit 1
            [ -n "$(find -L "/proc/$$/fd/3" -prune -type f -links 1)" ] || exit 1
            cat <&3' sh "$1"
    else
        plain_entry "$1" || return 1
        before=$(ls -id "$1" | awk '{ print $1 }')
        content=$(bounded cat "$1") || return 1
        plain_entry "$1" || return 1
        [ "$(ls -id "$1" | awk '{ print $1 }')" = "${before}" ] || return 1
        printf "%s\n" "${content}"
    fi
}

# True when $1 is a regular file with one link, no symlink.
plain_entry() {
    [ ! -h "$1" ] && [ -n "$(find "$1" -prune -type f -links 1 2>/dev/null)" ]
}

# Rename $1 to $2 with rename(2) semantics: never into a directory that $2
# (or a symlink at $2) names. GNU mv -T, BSD mv -h. A real directory at $2
# is refused ("link-to-dir"); a host whose mv has neither option is refused
# ("no_safe_rename": a plain mv could still move the file into a directory
# linked there in between). Afterwards $2 must be a plain file with $1's
# inode, else "race".
replace_entry() {
    inode=$(ls -id "$1" 2>/dev/null | awk '{ print $1 }')
    if mv -f -T "$1" "$2" 2>/dev/null || mv -f -h "$1" "$2" 2>/dev/null; then
        if [ -z "${inode}" ] || ! plain_entry "$2" \
            || [ "$(ls -id "$2" 2>/dev/null | awk '{ print $1 }')" != "${inode}" ]; then
            echo "Keyfile is unsafe (race), aborting."
            exit 1
        fi
        return 0
    fi
    rm -f "$1"
    if [ -d "$2" ] && [ ! -h "$2" ]; then
        echo "Keyfile is unsafe (link-to-dir), aborting."
    else
        echo "Keyfile is unsafe (no_safe_rename), aborting: mv -T and mv -h failed or are unsupported."
    fi
    exit 1
}

# 16 random hex digits for a temp file name nobody can predict; fails
# (prints nothing) unless od really produced exactly 16 hex digits.
random_suffix() {
    suffix=$(od -An -N8 -tx1 /dev/urandom 2>/dev/null | tr -d ' \n') || return 1
    case "${suffix}" in
        *[!0-9a-f]*) return 1 ;;
    esac
    [ "${#suffix}" -eq 16 ] || return 1
    printf "%s" "${suffix}"
}

# Vendor platforms whose authorized_keys ssm must not manage (host-wide).
platform_condition() {
    # PfSense
    if grep -qs "pfSense" "/etc/platform"; then
        echo "Product is pfSense"
        return 0
    fi

    # Truenas core
    if uname -a | grep -qs "TRUENAS"; then
        echo "Product is Truenas Core"
        return 0
    fi

    # Truenas Scale
    if uname -a | grep -qs "+truenas "; then
        echo "Product is Truenas Scale"
        return 0
    fi

    # Sophos
    if [ -f "/etc/product" ] && grep -qs "Sophos UTM" "/etc/product"; then
        echo "Product is Sophos UTM"
        return 0
    fi
}

get_authorized_keyfile_for() {
    login="$1"
    keyfile_location=$(get_authorized_keys_location "${login}")

    # never read through a link (a user could point it at /etc/shadow)
    if [ -n "$(keyfile_unsafe "${login}")" ]; then
        exit 0
    fi

    if [ ! -e "${keyfile_location}" ]; then
        echo "Couldn't find authorized_keys for this login."
        echo "Tried location: ${keyfile_location}"
        exit 1
    fi

    read_keyfile "${keyfile_location}" || exit 1
    echo ""
    exit 0
}

# Create a login's missing ~/.ssh as root: 0700 (umask 077), owned by the
# login's uid/gid from getent. Only inside a home that exists and is no
# symlink. mkdir never follows a link planted at .ssh (any existing entry
# makes it fail); ssm then enters the new directory, re-checks it with
# pwd -P (a link swapped in after the mkdir resolves elsewhere) and chowns
# its cwd ("."), never a path. An existing ~/.ssh is left alone.
# True when the login (uid $2, gid $3) could rename its home $1 away: the
# parent is the user's own and owner-writable, group-writable with the
# login's primary group, or world-writable (sticky or not: the user owns the
# home entry). Supplementary groups are not checked. Root (uid 0) is exempt.
home_parent_writable() {
    [ "$2" != "0" ] || return 1
    parent="${1%/*}"
    [ -n "${parent}" ] || parent="/"
    [ -n "$(find "${parent}" -prune \( \( -user "$2" -perm -200 \) -o \( -group "$3" -perm -020 \) \
        -o -perm -002 \) -print 2>/dev/null)" ]
}

ensure_ssh_dir() {
    entry=$(do_getent_passwd "$1") || entry=""
    home=$(printf "%s" "${entry}" | cut -d: -f6)
    if [ -n "${home}" ] && { [ -e "${home}/.ssh" ] || [ -h "${home}/.ssh" ]; }; then
        return 0
    fi
    if [ -z "${home}" ] || [ -h "${home}" ] || [ ! -d "${home}" ]; then
        echo "Keyfile is unsafe (home), aborting."
        exit 1
    fi
    uid=$(printf "%s" "${entry}" | cut -d: -f3)
    gid=$(printf "%s" "${entry}" | cut -d: -f4)
    case "${uid}:${gid}" in
        :*|*:|*[!0-9:]*) echo "Keyfile is unsafe (home), aborting."; exit 1 ;;
    esac
    real_home=$(cd "${home}" 2>/dev/null && pwd -P) || real_home=""
    if [ -z "${real_home}" ] || home_parent_writable "${real_home}" "${uid}" "${gid}"; then
        echo "Keyfile is unsafe (home), aborting."
        exit 1
    fi
    if ! (
        cd "${home}" || exit 1
        # still the home resolved above (not swapped since)
        [ "$(pwd -P)" = "${real_home}" ] || exit 1
        (umask 077 && mkdir .ssh) || exit 1
        cd .ssh || exit 1
        [ "$(pwd -P)" = "${real_home}/.ssh" ] || exit 1
        # still ssm's fresh directory (empty, root-owned, rwx for root, nothing
        # for group/other; a setgid bit inherited from the home is fine), not
        # one the user renamed in after the mkdir: the cwd is pinned
        [ -z "$(ls -A)" ] || exit 1
        [ -n "$(find . -prune -user 0 -perm -700 ! -perm -040 ! -perm -020 ! -perm -010 \
            ! -perm -004 ! -perm -002 ! -perm -001)" ] || exit 1
        chown "${uid}:${gid}" . || exit 1
    ); then
        echo "Keyfile is unsafe (ssh_dir), aborting."
        exit 1
    fi
}

handle_set_authorized_keyfile() {
    login="$1"

    readonly_condition=$(check_keyfile_condition "${login}")
    if [ -n "${readonly_condition}" ]; then
        echo "Keyfile is readonly, aborting."
        exit 1
    fi

    # A login that is not the SSH user ($2, the login ssm connects with) but
    # resolves to its home (a uid-0 alias such as toor in root's home) would
    # replace the file that holds ssm's own key: refused, never managed.
    # The check is never skipped: without a known SSH user it is impossible.
    ssh_user="${2:-}"
    own_home=""
    if [ -n "${ssh_user}" ]; then
        own_home=$(resolved_home "${ssh_user}")
    fi
    if [ -z "${own_home}" ]; then
        echo "Keyfile is unsafe (ssh_user), aborting."
        exit 1
    fi
    if [ "${ssh_user}" != "${login}" ] && [ "$(resolved_home "${login}")" = "${own_home}" ]; then
        echo "Keyfile is unsafe (shared_home), aborting."
        exit 1
    fi

    # a login without ~/.ssh gets one (never through a link)
    ensure_ssh_dir "${login}"

    # ~/.ssh itself a link: the write would land elsewhere, refuse. A linked
    # authorized_keys is fine: its entry is replaced, never written through.
    unsafe=$(keyfile_unsafe "${login}")
    if [ "${unsafe}" = "ssh_dir" ]; then
        echo "Keyfile is unsafe (ssh_dir), aborting."
        exit 1
    fi

    home=$(login_home "${login}")

    # Work inside the real ~/.ssh with relative names only: the cwd stays on
    # that directory even if the user swaps the path to a link afterwards.
    cd "${home}/.ssh" || { echo "Couldn't enter ${home}/.ssh"; exit 1; }
    if [ "$(pwd -P)" != "$(cd "${home}" && pwd -P)/.ssh" ]; then
        echo "Keyfile is unsafe (ssh_dir), aborting."
        exit 1
    fi

    # $3: the sha256 of the file as the listing read it. A file changed or
    # removed since is not overwritten (the caller decides on fresh data).
    expected_sha="${3:-}"
    if [ -n "${expected_sha}" ]; then
        current_sha="absent"
        if [ -z "${unsafe}" ] && [ -f authorized_keys ]; then
            current=$(read_keyfile authorized_keys) || current=""
            current_sha=$(printf "%s" "${current}" | content_sha)
        fi
        if [ "${current_sha}" != "${expected_sha}" ]; then
            echo "Keyfile changed since it was read (stale), aborting."
            exit 1
        fi
    fi

    # every name ssm creates here must be unpredictable
    suffix=$(random_suffix) || { echo "No random name available (od failed), aborting."; exit 1; }
    tmp_suffix=$(random_suffix) || { echo "No random name available (od failed), aborting."; exit 1; }

    # A handwritten plain file is kept: renamed to a fresh, unpredictable
    # name (never into a directory a planted authorized_keys.backup names).
    # Its header is read only from a plain single-link file, time-bounded.
    if [ -z "${unsafe}" ] && [ -f authorized_keys ]; then
        content=$(read_keyfile authorized_keys) || content=""
        file_head="${content%%
*}"
        if [ "${file_head}" != "${keyfile_head}" ]; then
            replace_entry authorized_keys "authorized_keys.backup.${suffix}"
        fi
    fi

    # A fresh, unpredictable name opened with O_CREAT|O_EXCL (noclobber):
    # nothing can be waiting there, and a link put there later is never
    # written through. Root-owned 0644 (umask 022), as the old script wrote
    # it; sshd StrictModes accepts root- or user-owned, not group/world
    # writable files.
    tmp=".authorized_keys.ssm.${tmp_suffix}"
    if ! (umask 022 && set -C && { printf "%s\n" "${keyfile_head}"; cat -; } > "${tmp}"); then
        echo "Couldn't create a temporary keyfile in ${home}/.ssh"
        exit 1
    fi
    replace_entry "${tmp}" authorized_keys
    exit 0
}

# Logins with an authorized_keys, the first one per home only. The homes
# seen are kept in a variable (no temp file: this runs as root).
get_ssh_users() {
    do_getent_passwd_all | {
        seen="
"
        while IFS=: read -r name _password _uid _gid _gecos home _shell; do
            if [ -e "${home}/${authorized_keys_location}" ]; then
                case "${seen}" in
                    *"
${home}
"*) ;;
                    *) echo "${name}"; seen="${seen}${home}
" ;;
                esac
            fi
        done
    }
    exit 0
}

# Encode stdin as the body of a JSON string (RFC 8259): backslash and double
# quote are escaped, tab/CR become \t/\r, every other C0 byte \u00XX, and
# lines are joined with \n. Byte-wise (LC_ALL=C), so any awk gives the same.
json_escape() {
    LC_ALL=C awk '
        BEGIN {
            for (i = 1; i < 32; i++) esc[sprintf("%c", i)] = sprintf("\\u%04x", i)
            esc["\t"] = "\\t"; esc["\r"] = "\\r"; esc["\\"] = "\\\\"; esc["\""] = "\\\""
        }
        {
            out = ""
            n = length($0)
            for (j = 1; j <= n; j++) {
                c = substr($0, j, 1)
                out = out ((c in esc) ? esc[c] : c)
            }
            printf "%s%s", (NR > 1 ? "\\n" : ""), out
        }'
}

# Which marker makes a login readonly, checked in the order of
# check_keyfile_condition: "system" (system_readonly, host-wide), "platform"
# (pfSense, TrueNAS, Sophos; host-wide), "user" (the login's own
# user_readonly, root-owned) or "".
keyfile_condition_scope() {
    login="$1"
    if [ -f "${HOME}/.ssh/system_readonly" ]; then
        echo "system"
        return 0
    fi
    if [ -n "$(platform_condition)" ]; then
        echo "platform"
        return 0
    fi
    if [ "$(user_readonly_state "${login}")" = "root" ]; then
        echo "user"
    fi
}

handle_get_ssh_keyfiles() {
    isFirst=true
    printf "["
      get_ssh_users | while read -r login; do
            # a read that failed (a link swapped in, a timeout, the file
            # deleted) is reported as "race", never shown; the listing goes on
            raced=""
            keyfile=$(get_authorized_keyfile_for "${login}") || { keyfile=""; raced="race"; }
            if [ "${isFirst}" = true ]; then
                isFirst=false
            else
                printf ','
            fi

            has_pragma="false"
            readonly_condition=$(check_keyfile_condition "${login}")

            # When file is readonly there is no point in checking the pragma
            if [ -n "${readonly_condition}" ]; then
                has_pragma="true"
            else
                head=$(printf "%s" "${keyfile}" | head -n1)
                [ "${head}" = "${keyfile_head}" ] && has_pragma="true"
            fi

            readonly_scope=$(keyfile_condition_scope "${login}")
            readonly_ignored=""
            case "$(user_readonly_state "${login}")" in
                other) readonly_ignored="user_readonly not owned by root" ;;
                link) readonly_ignored="user_readonly is a link" ;;
                tampered) readonly_ignored="user_readonly unsafe (tampered?): ~/.ssh not root-owned or writable by others, or the marker is an ssm keyfile" ;;
            esac
            unsafe=$(keyfile_unsafe "${login}")
            [ -n "${unsafe}" ] || unsafe="${raced}"
            # sha256 of exactly what was read: a write can check it is unchanged
            sha=""
            [ -n "${unsafe}" ] || sha=$(printf "%s" "${keyfile}" | content_sha)

            printf '{"login":"%s", "has_pragma": %s, "readonly_condition": "%s", "readonly_scope": "%s", "readonly_ignored": "%s", "unsafe": "%s",' \
                "$(printf "%s" "${login}" | json_escape)" "${has_pragma}" \
                "$(printf "%s" "${readonly_condition}" | json_escape)" "${readonly_scope}" \
                "${readonly_ignored}" "${unsafe}"

            # every string field is JSON-escaped (json_escape)
            printf '"sha256":"%s",' "${sha}"
            printf '"keyfile":"%s"}' "$(printf "%s" "${keyfile}" | json_escape)"
      done
    printf "]"
}

# "yes" when anything sits at the login's ~/.ssh/authorized_keys (a link
# too, dangling or not) or its ~/.ssh is a link, else "no". "unknown" (exit
# 1) when getent does not know the login or its home does not exist: an
# LDAP outage or an unmounted home must not look like "no file". Nothing
# is read.
handle_has_keyfile() {
    home=$(login_home "$1") || home=""
    if [ -z "${home}" ] || { [ ! -e "${home}" ] && [ ! -h "${home}" ]; }; then
        echo "unknown"
        exit 1
    fi
    if [ -e "${home}/${authorized_keys_location}" ] \
        || [ -h "${home}/${authorized_keys_location}" ] || [ -h "${home}/.ssh" ]; then
        echo "yes"
    else
        echo "no"
    fi
    exit 0
}

handle_update() {
    newfile="${0}.new"
    cat - > "${newfile}"
    # Can we check if the new file is valid?
    mv "${newfile}" "${0}"
    exit 0
}

handle_version() {
    sha256=$(sha256sum "${0}" | awk '{ print $1 }')
    printf '{"version":"%s","sha256":"%s"}' "${version}" "${sha256}"
    exit 0
}

#####################################
# Script starts here
#####################################

# Modify the command handling section
if [ $# -eq 0 ]; then
    printf "No command argument found"
    exit 2
fi

command="$1"
shift
case "${command}" in
    set_authorized_keyfile)  handle_set_authorized_keyfile "$@" ;;
    get_ssh_keyfiles)        handle_get_ssh_keyfiles ;;
    has_keyfile)             handle_has_keyfile "$@" ;;
    update)                  handle_update ;;
    version)                 handle_version ;;
    *)
        printf "Command '%s' not found.\n" "${command}"
        exit 2
        ;;
esac
