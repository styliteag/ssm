#!/usr/bin/env sh

set -eu

# shellcheck disable=SC3040
(set -o pipefail 2> /dev/null) && set -o pipefail

authorized_keys_location=".ssh/authorized_keys"
version="Secure SSH Manager script v0.3-alpha"
keyfile_head="# Auto-generated by Secure SSH Manager. DO NOT EDIT!"

have_getent() {
  command -v getent >/dev/null 2>&1
}

do_getent_passwd_all() {
  if have_getent; then
    getent passwd
  else
    cat /etc/passwd
  fi
}

# Without getent (busybox) the login must match field 1 exactly: a regex
# would let "roo." match root. ENVIRON, not awk -v (no escape processing).
# A login starting with "-" (or empty) is never looked up: getent would read
# it as an option. Not "getent passwd -- login": BSD getent takes "--" as a
# key and stops at the first one it does not find.
do_getent_passwd() {
  login="$1"
  case "${login}" in
    ""|-*) return 2 ;;
  esac
  if have_getent; then
    getent passwd "${login}"
  else
    ssm_login="${login}" LC_ALL=C awk -F: \
      'BEGIN { r = 2 } $1 == ENVIRON["ssm_login"] { print; r = 0; exit } END { exit r }' /etc/passwd
  fi
}

# TODO: Read authorized_keys location from sshd config
# Get the location of the authorized keyfile given a login
get_authorized_keys_location() {
  login="$1"
  home=$(do_getent_passwd "${login}" | cut -d: -f6)
  
  echo "${home}/${authorized_keys_location}"
}

# Check if the system has any condition that make the keyfile externally
# managed or readonly. Returns only the first met condition
check_keyfile_condition() {
    login="$1"

    # Check for global override
    system_readonly="${HOME}/.ssh/system_readonly"
    if [ -f "${system_readonly}" ]; then
        content=$(cat "${system_readonly}")
        if [ -n "${content}" ]; then
            printf "%s" "${content}"
        else
            printf "Global overrride '%s' exists" "${system_readonly}"
        fi
        return 0
    fi
    
    # Check for specific systems (host-wide, before any per-login marker)
    platform=$(platform_condition)
    if [ -n "${platform}" ]; then
        printf "%s" "${platform}"
        return 0
    fi

    # Check for user override (only a plain root-owned marker counts). Its
    # content is never shown: a marker could be a link to any file.
    if [ "$(user_readonly_state "${login}")" = "root" ]; then
        printf "user_readonly (root-owned)"
        return 0
    fi

    # A firewall writes the file from its configuration: only a login that
    # is a user there can be managed
    if firewall_driver && [ -z "$(firewall_user "${login}")" ]; then
        printf "%s" "${firewall_not_configured}"
        return 0
    fi
}

# Path of a login's user_readonly marker.
user_readonly_file() {
    home=$(do_getent_passwd "$1" | cut -d: -f6)
    printf "%s" "${home}/.ssh/user_readonly"
}

# State of a login's user_readonly: "root" (a plain file owned by uid 0 with
# one link, in a ~/.ssh that is no link: honoured), "link" (a symlink or
# hardlink, or ~/.ssh is unsafe: ignored), "other" (owned by someone else:
# ignored, the login's user could freeze their own revocation), "tampered"
# (root-owned, but in a ~/.ssh that root does not own or that group/other
# can write — the user could have renamed any root-owned file there, such
# as ssm's own authorized_keys, to user_readonly — or the marker is an
# ssm-written keyfile: ignored and reported) or "" (none).
# find -user/-links/-type/-perm are POSIX (GNU, busybox, BSD), unlike stat.
user_readonly_state() {
    marker=$(user_readonly_file "$1")
    if [ ! -e "${marker}" ] && [ ! -h "${marker}" ]; then
        return 0
    fi
    if [ -h "${marker}" ] || [ -n "$(ssh_dir_unsafe "$1")" ] \
        || [ -z "$(find "${marker}" -prune -type f -links 1 2>/dev/null)" ]; then
        echo "link"
    elif [ -z "$(find "${marker}" -prune -user 0 2>/dev/null)" ]; then
        echo "other"
    elif [ -z "$(find "${marker%/*}" -prune -user 0 ! -perm -020 ! -perm -002 2>/dev/null)" ]; then
        echo "tampered"
    # only now read (plain, root-owned, in a directory only root can change)
    elif [ "$(bounded head -n 1 "${marker}" 2>/dev/null)" = "${keyfile_head}" ]; then
        echo "tampered"
    else
        echo "root"
    fi
}

# Home dir of a login (getent passwd field 6).
login_home() {
    do_getent_passwd "$1" | cut -d: -f6
}

# Home of a login with every symlink resolved (pwd -P), else the getent
# field as it is; "" for an unknown login.
resolved_home() {
    home=$(login_home "$1") || return 0
    [ -n "${home}" ] || return 0
    (cd "${home}" 2>/dev/null && pwd -P) || printf "%s\n" "${home}"
}

# "ssh_dir" when the login's ~/.ssh is a symlink or does not resolve to the
# .ssh directory inside its (resolved) home, else "". A home that is itself
# reached through a symlink (FreeBSD /home -> /usr/home) is fine.
ssh_dir_unsafe() {
    home=$(login_home "$1")
    dir="${home}/.ssh"
    if [ -h "${dir}" ]; then
        echo "ssh_dir"
        return 0
    fi
    if [ -d "${dir}" ]; then
        real_home=$(cd "${home}" 2>/dev/null && pwd -P) || real_home=""
        real_dir=$(cd "${dir}" 2>/dev/null && pwd -P) || real_dir=""
        if [ -z "${real_home}" ] || [ "${real_dir}" != "${real_home}/.ssh" ]; then
            echo "ssh_dir"
        fi
    fi
}

# Why ssm (running as root) must not read a login's authorized_keys:
# "ssh_dir" (~/.ssh is a link: not written either), "symlink", "hardlink"
# (more than one link) or "special" (not a regular file) — these three are
# replaced by a write, never written through — or "" (safe).
keyfile_unsafe() {
    dir_state=$(ssh_dir_unsafe "$1")
    if [ -n "${dir_state}" ]; then
        echo "${dir_state}"
        return 0
    fi
    file="$(login_home "$1")/${authorized_keys_location}"
    if [ -h "${file}" ]; then
        echo "symlink"
    elif [ ! -e "${file}" ]; then
        return 0
    elif [ ! -f "${file}" ]; then
        echo "special"
    elif [ -n "$(find "${file}" -prune -links +1 2>/dev/null)" ]; then
        echo "hardlink"
    fi
}

# Run "$@" with a time limit where timeout(1) exists (a FIFO swapped in
# must not hang the script).
bounded() {
    if command -v timeout >/dev/null 2>&1; then
        timeout 10 "$@"
    else
        "$@"
    fi
}

# sha256 (hex) of stdin; "" without sha256sum (no check then).
content_sha() {
    if command -v sha256sum >/dev/null 2>&1; then
        sha256sum | awk '{ print $1 }'
    else
        cat >/dev/null
    fi
}

# True when perl can open with O_NOFOLLOW|O_NONBLOCK (Fcntl).
have_nofollow_perl() {
    command -v perl >/dev/null 2>&1 \
        && perl -MFcntl=O_RDONLY,O_NOFOLLOW,O_NONBLOCK -e 1 >/dev/null 2>&1
}

# Print a plain authorized_keys. With perl, the file is opened with
# O_NOFOLLOW|O_NONBLOCK (a link swapped in after the checks is never
# followed, nothing behind it is opened, a FIFO cannot block) and the
# opened file must be a regular file with one link and the very inode of the
# directory entry. Without perl on Linux the opened file is checked the same
# way through /proc/<pid>/fd (the open itself follows a link). Elsewhere the
# entry is checked before and after the read (same inode, plain, one link):
# a link swapped in and back in between is not seen (documented limitation).
read_keyfile() {
    if have_nofollow_perl; then
        # shellcheck disable=SC2016
        bounded perl -MFcntl=O_RDONLY,O_NOFOLLOW,O_NONBLOCK -e '
            my $p = shift;
            sysopen(my $fh, $p, O_RDONLY | O_NOFOLLOW | O_NONBLOCK) or exit 1;
            my @f = stat($fh) or exit 1;
            -f _ or exit 1;
            $f[3] == 1 or exit 1;
            my @l = lstat($p) or exit 1;
            ($f[0] == $l[0] && $f[1] == $l[1]) or exit 1;
            binmode($fh);
            binmode(STDOUT);
            local $/;
            my $c = <$fh>;
            defined($c) or $c = "";
            print $c or exit 1;
            exit 0;' "$1"
    elif [ -d /proc/self/fd ]; then
        # shellcheck disable=SC2016
        bounded sh -c '
            exec 3< "$1" || exit 1
            opened=$(ls -iL "/proc/$$/fd/3" | awk "{ print \$1 }")
            entry=$(ls -id "$1" | awk "{ print \$1 }")
            [ "${opened}" = "${entry}" ] || exit 1
            [ -n "$(find -L "/proc/$$/fd/3" -prune -type f -links 1)" ] || exit 1
            cat <&3' sh "$1"
    else
        plain_entry "$1" || return 1
        before=$(ls -id "$1" | awk '{ print $1 }')
        content=$(bounded cat "$1") || return 1
        plain_entry "$1" || return 1
        [ "$(ls -id "$1" | awk '{ print $1 }')" = "${before}" ] || return 1
        printf "%s\n" "${content}"
    fi
}

# True when $1 is a regular file with one link, no symlink.
plain_entry() {
    [ ! -h "$1" ] && [ -n "$(find "$1" -prune -type f -links 1 2>/dev/null)" ]
}

# Rename $1 to $2 with rename(2) semantics: never into a directory that $2
# (or a symlink at $2) names. GNU mv -T, BSD mv -h. A real directory at $2
# is refused ("link-to-dir"); a host whose mv has neither option is refused
# ("no_safe_rename": a plain mv could still move the file into a directory
# linked there in between). Afterwards $2 must be a plain file with $1's
# inode, else "race".
replace_entry() {
    inode=$(ls -id "$1" 2>/dev/null | awk '{ print $1 }')
    if mv -f -T "$1" "$2" 2>/dev/null || mv -f -h "$1" "$2" 2>/dev/null; then
        if [ -z "${inode}" ] || ! plain_entry "$2" \
            || [ "$(ls -id "$2" 2>/dev/null | awk '{ print $1 }')" != "${inode}" ]; then
            echo "Keyfile is unsafe (race), aborting."
            exit 1
        fi
        return 0
    fi
    rm -f "$1"
    if [ -d "$2" ] && [ ! -h "$2" ]; then
        echo "Keyfile is unsafe (link-to-dir), aborting."
    else
        echo "Keyfile is unsafe (no_safe_rename), aborting: mv -T and mv -h failed or are unsupported."
    fi
    exit 1
}

# 16 random hex digits for a temp file name nobody can predict; fails
# (prints nothing) unless od really produced exactly 16 hex digits.
random_suffix() {
    suffix=$(od -An -N8 -tx1 /dev/urandom 2>/dev/null | tr -d ' \n') || return 1
    case "${suffix}" in
        *[!0-9a-f]*) return 1 ;;
    esac
    [ "${#suffix}" -eq 16 ] || return 1
    printf "%s" "${suffix}"
}

# ---------------------------------------------------------------------------
# Firewalls (OPNsense, pfSense). The box writes every authorized_keys from
# its configuration (config.xml, field authorizedkeys of the user), so a
# file ssm wrote would be replaced at the next change. There ssm writes the
# field with the box's own PHP code and lets the box write the file:
#   OPNsense  model OPNsense\Auth\User, then "configctl auth sync user"
#   pfSense   system/user in the configuration, local_user_set, write_config
# Reads stay on the file (it is what sshd uses). A login is managed only
# when a user of the configuration has its uid (root on OPNsense; admin on
# pfSense, whose keys the login root uses too); any other login is readonly.
# ---------------------------------------------------------------------------

firewall_marker=".ssm_managed"
firewall_not_configured="not a user in the firewall's configuration"

# "opnsense", "pfsense" or "". SSM_SYSROOT is a prefix for the tests.
firewall_kind() {
    sysroot="${SSM_SYSROOT:-}"
    if [ -f "${sysroot}/usr/local/opnsense/version/core" ]; then
        echo "opnsense"
    elif grep -qs "pfSense" "${sysroot}/etc/platform"; then
        echo "pfsense"
    fi
}

# True on a firewall whose configuration ssm can change: php is there, on
# OPNsense configctl too. php and configctl come from root's PATH, which
# only root can change.
firewall_driver() {
    case "$(firewall_kind)" in
        opnsense) command -v php >/dev/null 2>&1 && command -v configctl >/dev/null 2>&1 ;;
        pfsense) command -v php >/dev/null 2>&1 ;;
        *) return 1 ;;
    esac
}

# firewall_php <op> [user] [keys]: the box's PHP code for "users" (lines
# "uid:name"), "get" (the keys of the user, plain text) or "set" (keys
# become the user's keys). Exit 3: no such user. Values travel in php's
# environment (set on the php command itself: an assignment in front of a
# shell function is not exported by every sh), never in the code. php runs
# in "/", never in a login's ~/.ssh: it looks for its include files in the
# current directory too, and a user could put one there. Its messages go to
# stderr, so they never count as keys.
firewall_php() {
    case "$(firewall_kind)" in
        opnsense)
            (cd / && SSM_FW_OP="$1" SSM_FW_USER="${2:-}" SSM_FW_KEYS="${3:-}" \
                php -d display_errors=stderr <<'PHP'
<?php
require_once("legacy_bindings.inc");
use OPNsense\Core\Config;
$op = (string)getenv("SSM_FW_OP");
$name = (string)getenv("SSM_FW_USER");
if ($op === "users") {
    foreach (Config::getInstance()->object()->system->user as $u) {
        echo (string)$u->uid . ":" . (string)$u->name . "\n";
    }
    exit(0);
}
if ($op === "set") {
    Config::getInstance()->lock();
}
$mdl = new OPNsense\Auth\User();
$user = $mdl->getUserByName($name);
if (!$user) {
    exit(3);
}
if ($op === "get") {
    echo (string)$user->authorizedkeys;
    exit(0);
}
if ($op === "set") {
    // the model field is plain text and does the base64 itself
    $user->authorizedkeys = (string)getenv("SSM_FW_KEYS");
    $mdl->serializeToConfig(false, true);
    Config::getInstance()->save();
    exit(0);
}
exit(2);
PHP
            )
            ;;
        pfsense)
            (cd / && SSM_FW_OP="$1" SSM_FW_USER="${2:-}" SSM_FW_KEYS="${3:-}" \
                php -d display_errors=stderr <<'PHP'
<?php
require_once("globals.inc");
require_once("config.inc");
require_once("functions.inc");
require_once("auth.inc");
$op = (string)getenv("SSM_FW_OP");
$name = (string)getenv("SSM_FW_USER");
$users = config_get_path("system/user", []);
if ($op === "users") {
    foreach ($users as $u) {
        echo ($u["uid"] ?? "") . ":" . ($u["name"] ?? "") . "\n";
    }
    exit(0);
}
foreach ($users as $i => $u) {
    if (($u["name"] ?? "") !== $name) {
        continue;
    }
    if ($op === "get") {
        echo str_replace("\r", "", (string)base64_decode($u["authorizedkeys"] ?? ""));
        exit(0);
    }
    if ($op === "set") {
        // the field is base64 of the lines, joined with CRLF as the GUI does
        $keys = str_replace("\n", "\r\n", str_replace("\r", "", (string)getenv("SSM_FW_KEYS")));
        $users[$i]["authorizedkeys"] = base64_encode($keys);
        config_set_path("system/user", $users);
        local_user_set($users[$i]);
        write_config("ssm: SSH keys of " . $name);
        exit(0);
    }
    exit(2);
}
exit(3);
PHP
            )
            ;;
        *) return 2 ;;
    esac
}

# Sets FW_USERS ("uid:name" lines of the configuration) once, in the main
# shell, before any $(...) asks firewall_user. Empty when it cannot be read:
# then every login is readonly.
FW_USERS=""
firewall_load() {
    if firewall_driver; then
        FW_USERS=$(firewall_php users 2>/dev/null) || FW_USERS=""
    fi
}

# The configuration's user that carries a login's keys ("" when there is
# none): the user with the login's name and uid. One exception: on pfSense
# the login root has no user of its own, its keys are those of the uid-0
# user (admin). A uid that two users of the configuration share is never
# mapped, and neither is a name outside [A-Za-z0-9._-] (it is handed to
# configctl). uid and name are compared as text.
firewall_user() {
    uid=$(do_getent_passwd "$1" | cut -d: -f3) || uid=""
    case "${uid}" in
        ""|*[!0-9]*) return 0 ;;
    esac
    name=$(printf "%s\n" "${FW_USERS}" | ssm_uid="${uid}" LC_ALL=C awk '
        {
            colon = index($0, ":")
            if (colon == 0) next
            if ((substr($0, 1, colon - 1) "") == (ENVIRON["ssm_uid"] "")) {
                n++
                name = substr($0, colon + 1)
            }
        }
        END { if (n == 1) print name }')
    case "${name}" in
        ""|*[!A-Za-z0-9._-]*) return 0 ;;
    esac
    login_ok "${name}" || return 0
    if [ "${name}" = "$1" ] \
        || { [ "$1" = "root" ] && [ "${uid}" = "0" ] && [ "$(firewall_kind)" = "pfsense" ]; }; then
        printf "%s" "${name}"
    fi
}

# The key material (base64 blobs) of the lines on stdin, sorted.
key_blobs() {
    tr -d '\r' | LC_ALL=C awk '{
        for (i = 1; i <= NF; i++) if ($i ~ /^AAAA[A-Za-z0-9+\/=]+$/) { print $i; break }
    }' | LC_ALL=C sort -u
}

# True when every non-empty line on stdin is a key line: a known key type
# followed by its base64 blob (options may stand before it). Anything else
# must never reach the configuration: an unusable value there locks every
# key of the user out.
firewall_lines_ok() {
    tr -d '\r' | LC_ALL=C awk '
        /^[ \t]*$/ { next }
        {
            ok = 0
            for (i = 1; i < NF; i++) {
                if ($i ~ /^(ssh-rsa|ssh-dss|ssh-ed25519|ecdsa-sha2-nistp(256|384|521)|sk-ssh-ed25519@openssh\.com|sk-ecdsa-sha2-nistp256@openssh\.com)$/ \
                    && $(i + 1) ~ /^AAAA[A-Za-z0-9+\/=]+$/) { ok = 1; break }
            }
            if (!ok) { bad = 1; exit }
        }
        END { exit bad ? 1 : 0 }'
}

# Write $2 as the keys of the configuration's user $1 and let the box
# write the file.
firewall_write() {
    firewall_php set "$1" "$2" >/dev/null 2>&1 || return 1
    if [ "$(firewall_kind)" = "opnsense" ]; then
        configctl auth sync user "$1" >/dev/null 2>&1 || return 1
    fi
}

# True when ./authorized_keys holds exactly the keys of $1 (the box writes
# the file itself: give it a moment).
firewall_file_has() {
    wanted=$(printf "%s\n" "$1" | key_blobs)
    for _try in 1 2 3 4 5; do
        found=""
        if [ -e authorized_keys ] || [ -h authorized_keys ]; then
            if content=$(read_keyfile authorized_keys); then
                found=$(printf "%s\n" "${content}" | key_blobs)
            else
                found="unreadable"
            fi
        fi
        [ "${found}" = "${wanted}" ] && return 0
        sleep 1
    done
    return 1
}

# set_authorized_keyfile on a firewall, called in the login's real ~/.ssh
# after every check of the plain write: stdin becomes the keys of the
# login's user in the configuration. The keys from before are kept in a
# backup file at the first write, and put back when the box does not end up
# with the new ones in the file (ssm would lose its own access otherwise).
# The box writes the file by its path and follows a link there, so a linked
# or otherwise unsafe authorized_keys ($2, keyfile_unsafe) is refused here
# (the plain write replaces such an entry; the box cannot). A link put
# there between this check and the box's write is still followed.
firewall_set_keys() {
    fw_user=$(firewall_user "$1")
    if [ -z "${fw_user}" ]; then
        echo "Keyfile is readonly, aborting."
        exit 1
    fi
    if [ -n "$2" ]; then
        echo "Keyfile is unsafe ($2), aborting: the firewall would write through it."
        exit 1
    fi
    new=$(cat -)
    if ! printf "%s\n" "${new}" | firewall_lines_ok; then
        echo "Keyfile is unsafe (firewall_lines), aborting: a line is not a key line."
        exit 1
    fi
    if ! old=$(firewall_php get "${fw_user}" 2>/dev/null); then
        echo "Couldn't read the keys of '${fw_user}' from the firewall's configuration"
        exit 1
    fi
    # the keys from before must be fit to be put back
    if ! printf "%s\n" "${old}" | firewall_lines_ok; then
        echo "Keyfile is unsafe (firewall_lines), aborting: the configuration holds a line that is not a key line."
        exit 1
    fi
    if [ -h authorized_keys ] || { [ -e authorized_keys ] && ! plain_entry authorized_keys; }; then
        echo "Keyfile is unsafe (race), aborting."
        exit 1
    fi
    if [ ! -e "${firewall_marker}" ] && [ ! -h "${firewall_marker}" ] && [ -n "${old}" ]; then
        suffix=$(random_suffix) || { echo "No random name available (od failed), aborting."; exit 1; }
        if ! (umask 077 && set -C && printf "%s\n" "${old}" > "authorized_keys.backup.${suffix}"); then
            echo "Couldn't keep a backup of the firewall's keys, aborting."
            exit 1
        fi
    fi
    if ! firewall_write "${fw_user}" "${new}" || ! firewall_file_has "${new}"; then
        firewall_write "${fw_user}" "${old}" || true
        echo "The firewall did not take the keys of '${fw_user}' (keys from before put back), aborting."
        exit 1
    fi
    if [ ! -e "${firewall_marker}" ] && [ ! -h "${firewall_marker}" ]; then
        (umask 077 && set -C && : > "${firewall_marker}") 2>/dev/null || true
    fi
    exit 0
}

# Vendor platforms whose authorized_keys ssm must not manage (host-wide).
platform_condition() {
    # A firewall without php: nothing ssm could write the configuration
    # with, and a file ssm wrote would be replaced by the box
    if [ -n "$(firewall_kind)" ] && ! firewall_driver; then
        if [ "$(firewall_kind)" = "pfsense" ]; then
            echo "Product is pfSense"
        else
            echo "Product is OPNsense"
        fi
        return 0
    fi

    # Truenas core
    if uname -a | grep -qs "TRUENAS"; then
        echo "Product is Truenas Core"
        return 0
    fi

    # Truenas Scale
    if uname -a | grep -qs "+truenas "; then
        echo "Product is Truenas Scale"
        return 0
    fi

    # Sophos
    if [ -f "/etc/product" ] && grep -qs "Sophos UTM" "/etc/product"; then
        echo "Product is Sophos UTM"
        return 0
    fi
}

get_authorized_keyfile_for() {
    login="$1"
    keyfile_location=$(get_authorized_keys_location "${login}")

    # never read through a link (a user could point it at /etc/shadow)
    if [ -n "$(keyfile_unsafe "${login}")" ]; then
        exit 0
    fi

    if [ ! -e "${keyfile_location}" ]; then
        echo "Couldn't find authorized_keys for this login."
        echo "Tried location: ${keyfile_location}"
        exit 1
    fi

    read_keyfile "${keyfile_location}" || exit 1
    echo ""
    exit 0
}

# Create a login's missing ~/.ssh as root: 0700 (umask 077), owned by the
# login's uid/gid from getent. Only inside a home that exists and is no
# symlink. mkdir never follows a link planted at .ssh (any existing entry
# makes it fail); ssm then enters the new directory, re-checks it with
# pwd -P (a link swapped in after the mkdir resolves elsewhere) and chowns
# its cwd ("."), never a path. An existing ~/.ssh is left alone.
# True when the login (uid $2, gid $3) could rename its home $1 away: the
# parent is the user's own and owner-writable, group-writable with the
# login's primary group, or world-writable (sticky or not: the user owns the
# home entry). Supplementary groups are not checked. Root (uid 0) is exempt.
home_parent_writable() {
    [ "$2" != "0" ] || return 1
    parent="${1%/*}"
    [ -n "${parent}" ] || parent="/"
    [ -n "$(find "${parent}" -prune \( \( -user "$2" -perm -200 \) -o \( -group "$3" -perm -020 \) \
        -o -perm -002 \) -print 2>/dev/null)" ]
}

ensure_ssh_dir() {
    entry=$(do_getent_passwd "$1") || entry=""
    home=$(printf "%s" "${entry}" | cut -d: -f6)
    if [ -n "${home}" ] && { [ -e "${home}/.ssh" ] || [ -h "${home}/.ssh" ]; }; then
        return 0
    fi
    if [ -z "${home}" ] || [ -h "${home}" ] || [ ! -d "${home}" ]; then
        echo "Keyfile is unsafe (home), aborting."
        exit 1
    fi
    uid=$(printf "%s" "${entry}" | cut -d: -f3)
    gid=$(printf "%s" "${entry}" | cut -d: -f4)
    case "${uid}:${gid}" in
        :*|*:|*[!0-9:]*) echo "Keyfile is unsafe (home), aborting."; exit 1 ;;
    esac
    real_home=$(cd "${home}" 2>/dev/null && pwd -P) || real_home=""
    if [ -z "${real_home}" ] || home_parent_writable "${real_home}" "${uid}" "${gid}"; then
        echo "Keyfile is unsafe (home), aborting."
        exit 1
    fi
    if ! (
        cd "${home}" || exit 1
        # still the home resolved above (not swapped since)
        [ "$(pwd -P)" = "${real_home}" ] || exit 1
        (umask 077 && mkdir .ssh) || exit 1
        cd .ssh || exit 1
        [ "$(pwd -P)" = "${real_home}/.ssh" ] || exit 1
        # still ssm's fresh directory (empty, root-owned, rwx for root, nothing
        # for group/other; a setgid bit inherited from the home is fine), not
        # one the user renamed in after the mkdir: the cwd is pinned
        [ -z "$(ls -A)" ] || exit 1
        [ -n "$(find . -prune -user 0 -perm -700 ! -perm -040 ! -perm -020 ! -perm -010 \
            ! -perm -004 ! -perm -002 ! -perm -001)" ] || exit 1
        chown "${uid}:${gid}" . || exit 1
    ); then
        echo "Keyfile is unsafe (ssh_dir), aborting."
        exit 1
    fi
}

# A login ssm may write: not empty, not all digits, no leading "+" or "-"
# (getent would read a uid, "+0" is root, or an option), no ":", "/",
# whitespace or control character. Ssm.Authorizations.Login.host_safe?/1
# refuses the same. tr with every byte listed: busybox 1.01 tr ignores octal ranges and old ash lacks [[:cntrl:]].
login_ok() {
    case "$1" in
        ""|-*|+*|*[:/]*) return 1 ;;
    esac
    [ "$(printf "%s" "$1" | tr -d '\001\002\003\004\005\006\007\010\011\012\013\014\015\016\017\020\021\022\023\024\025\026\027\030\031\032\033\034\035\036\037\040\177')" = "$1" ] || return 1
    case "$1" in
        *[!0-9]*) return 0 ;;
    esac
    return 1
}

handle_set_authorized_keyfile() {
    login="${1:-}"
    firewall_load

    if ! login_ok "${login}"; then
        echo "Keyfile is unsafe (invalid_login), aborting."
        exit 1
    fi
    # an unknown login or a relative home would resolve against the cwd
    home=$(login_home "${login}") || home=""
    case "${home}" in
        /*) ;;
        *) echo "Keyfile is unsafe (home), aborting."; exit 1 ;;
    esac

    readonly_condition=$(check_keyfile_condition "${login}")
    if [ -n "${readonly_condition}" ]; then
        echo "Keyfile is readonly, aborting."
        exit 1
    fi

    # The file in $HOME holds ssm's own key. Only a write for the SSH user
    # ($2, the login ssm connects with; ssm adds its key to that content)
    # may land there, and that write must land there. Any other login that
    # resolves to $HOME or to the SSH user's home (a uid-0 alias such as
    # toor in root's home) is refused, never managed. The check is never
    # skipped: without a known SSH user and $HOME it is impossible.
    ssh_user="${2:-}"
    own_home=""
    env_home=""
    if [ -n "${ssh_user}" ]; then
        own_home=$(resolved_home "${ssh_user}")
    fi
    if [ -n "${HOME:-}" ]; then
        env_home=$(cd "${HOME}" 2>/dev/null && pwd -P) || env_home=""
    fi
    if [ -z "${own_home}" ] || [ -z "${env_home}" ]; then
        echo "Keyfile is unsafe (ssh_user), aborting."
        exit 1
    fi
    target_home=$(resolved_home "${login}")
    if [ "${ssh_user}" = "${login}" ]; then
        if [ "${target_home}" != "${env_home}" ]; then
            echo "Keyfile is unsafe (ssh_user), aborting."
            exit 1
        fi
    elif [ "${target_home}" = "${own_home}" ] || [ "${target_home}" = "${env_home}" ]; then
        echo "Keyfile is unsafe (shared_home), aborting."
        exit 1
    fi

    # a login without ~/.ssh gets one (never through a link)
    ensure_ssh_dir "${login}"

    # ~/.ssh itself a link: the write would land elsewhere, refuse. A linked
    # authorized_keys is fine: its entry is replaced, never written through.
    unsafe=$(keyfile_unsafe "${login}")
    if [ "${unsafe}" = "ssh_dir" ]; then
        echo "Keyfile is unsafe (ssh_dir), aborting."
        exit 1
    fi

    home=$(login_home "${login}")

    # Work inside the real ~/.ssh with relative names only: the cwd stays on
    # that directory even if the user swaps the path to a link afterwards.
    cd "${home}/.ssh" || { echo "Couldn't enter ${home}/.ssh"; exit 1; }
    if [ "$(pwd -P)" != "$(cd "${home}" && pwd -P)/.ssh" ]; then
        echo "Keyfile is unsafe (ssh_dir), aborting."
        exit 1
    fi

    # $3: the sha256 of the file as the listing read it. A file changed or
    # removed since is not overwritten (the caller decides on fresh data).
    expected_sha="${3:-}"
    if [ -n "${expected_sha}" ]; then
        current_sha="absent"
        if [ -z "${unsafe}" ] && [ -f authorized_keys ]; then
            current=$(read_keyfile authorized_keys) || current=""
            current_sha=$(printf "%s" "${current}" | content_sha)
        fi
        if [ "${current_sha}" != "${expected_sha}" ]; then
            echo "Keyfile changed since it was read (stale), aborting."
            exit 1
        fi
    fi

    # a firewall writes the file itself, from its configuration
    if firewall_driver; then
        firewall_set_keys "${login}" "${unsafe}"
    fi

    # every name ssm creates here must be unpredictable
    suffix=$(random_suffix) || { echo "No random name available (od failed), aborting."; exit 1; }
    tmp_suffix=$(random_suffix) || { echo "No random name available (od failed), aborting."; exit 1; }

    # A handwritten plain file is kept: renamed to a fresh, unpredictable
    # name (never into a directory a planted authorized_keys.backup names).
    # Its header is read only from a plain single-link file, time-bounded.
    if [ -z "${unsafe}" ] && [ -f authorized_keys ]; then
        content=$(read_keyfile authorized_keys) || content=""
        file_head="${content%%
*}"
        if [ "${file_head}" != "${keyfile_head}" ]; then
            replace_entry authorized_keys "authorized_keys.backup.${suffix}"
        fi
    fi

    # A fresh, unpredictable name opened with O_CREAT|O_EXCL (noclobber):
    # nothing can be waiting there, and a link put there later is never
    # written through. Root-owned 0644 (umask 022), as the old script wrote
    # it; sshd StrictModes accepts root- or user-owned, not group/world
    # writable files.
    tmp=".authorized_keys.ssm.${tmp_suffix}"
    if ! (umask 022 && set -C && { printf "%s\n" "${keyfile_head}"; cat -; } > "${tmp}"); then
        echo "Couldn't create a temporary keyfile in ${home}/.ssh"
        exit 1
    fi
    replace_entry "${tmp}" authorized_keys
    exit 0
}

# The login ssm connected with (sshd sets LOGNAME), when it is one account
# with root on pfSense: there root and admin share uid 0 and /root, root
# comes first in the passwd file, and ssm may connect as either. "" else.
pfsense_ssh_login() {
    [ "$(firewall_kind)" = "pfsense" ] || return 0
    name="${LOGNAME:-}"
    login_ok "${name}" || return 0
    entry=$(do_getent_passwd "${name}") || return 0
    if [ "$(printf "%s" "${entry}" | cut -d: -f3)" = "0" ] \
        && [ "$(printf "%s" "${entry}" | cut -d: -f6)" = "${HOME:-}" ]; then
        printf "%s" "${name}"
    fi
}

# Logins with an authorized_keys, the first one per home only. The homes
# seen are kept in a variable (no temp file: this runs as root). On pfSense
# the file in $HOME is listed under the login ssm connected with (admin or
# root: one account), so it is the file of ssm's SSH user either way.
get_ssh_users() {
    own_login=$(pfsense_ssh_login)
    do_getent_passwd_all | {
        seen="
"
        while IFS=: read -r name _password _uid _gid _gecos home _shell; do
            if [ -e "${home}/${authorized_keys_location}" ]; then
                case "${seen}" in
                    *"
${home}
"*) ;;
                    *)
                        if [ -n "${own_login}" ] && [ "${home}" = "${HOME:-}" ]; then
                            echo "${own_login}"
                        else
                            echo "${name}"
                        fi
                        seen="${seen}${home}
" ;;
                esac
            fi
        done
    }
    exit 0
}

# Encode stdin as the body of a JSON string (RFC 8259): backslash and double
# quote are escaped, tab/CR become \t/\r, every other C0 byte \u00XX, and
# lines are joined with \n. Byte-wise (LC_ALL=C), so any awk gives the same.
json_escape() {
    LC_ALL=C awk '
        BEGIN {
            for (i = 1; i < 32; i++) esc[sprintf("%c", i)] = sprintf("\\u%04x", i)
            esc["\t"] = "\\t"; esc["\r"] = "\\r"; esc["\\"] = "\\\\"; esc["\""] = "\\\""
        }
        {
            out = ""
            n = length($0)
            for (j = 1; j <= n; j++) {
                c = substr($0, j, 1)
                out = out ((c in esc) ? esc[c] : c)
            }
            printf "%s%s", (NR > 1 ? "\\n" : ""), out
        }'
}

# Which marker makes a login readonly, checked in the order of
# check_keyfile_condition: "system" (system_readonly, host-wide), "platform"
# (pfSense without php, TrueNAS, Sophos; host-wide), "user" (the login's own
# user_readonly, root-owned, or a login a firewall's configuration does not
# know) or "".
keyfile_condition_scope() {
    login="$1"
    if [ -f "${HOME}/.ssh/system_readonly" ]; then
        echo "system"
        return 0
    fi
    if [ -n "$(platform_condition)" ]; then
        echo "platform"
        return 0
    fi
    if [ "$(user_readonly_state "${login}")" = "root" ]; then
        echo "user"
        return 0
    fi
    if firewall_driver && [ -z "$(firewall_user "${login}")" ]; then
        echo "user"
    fi
}

# Why a login ssm asks about has no listing entry: "unknown_login" (getent
# does not know it: LDAP/SSSD down), "home_missing" (the home does not exist:
# an unmounted pool on an inactive HA node), "home_unreadable" (not a
# directory root can enter), else "" (the home is there: no file).
home_state() {
    home=$(login_home "$1") || home=""
    if [ -z "${home}" ]; then
        echo "unknown_login"
    elif [ ! -e "${home}" ] && [ ! -h "${home}" ]; then
        echo "home_missing"
    elif [ ! -d "${home}" ] || [ ! -x "${home}" ] || [ ! -r "${home}" ]; then
        echo "home_unreadable"
    fi
}

# get_ssh_keyfiles [login ...]: every login with an authorized_keys, plus an
# entry with "home_state" for each given login whose home is not there, so
# an unreachable home never reads as "no keys".
handle_get_ssh_keyfiles() {
    firewall_load
    isFirst=true
    printf "["
    for login in "$@"; do
        login_ok "${login}" || continue
        state=$(home_state "${login}")
        [ -n "${state}" ] || continue
        if [ "${isFirst}" = true ]; then isFirst=false; else printf ','; fi
        printf '{"login":"%s", "has_pragma": false, "readonly_condition": "", "readonly_scope": "", "readonly_ignored": "", "unsafe": "", "home_state":"%s", "sha256":"", "keyfile":""}' \
            "$(printf "%s" "${login}" | json_escape)" "${state}"
    done
      get_ssh_users | while read -r login; do
            # a read that failed (a link swapped in, a timeout, the file
            # deleted) is reported as "race", never shown; the listing goes on
            raced=""
            keyfile=$(get_authorized_keyfile_for "${login}") || { keyfile=""; raced="race"; }
            if [ "${isFirst}" = true ]; then
                isFirst=false
            else
                printf ','
            fi

            has_pragma="false"
            readonly_condition=$(check_keyfile_condition "${login}")

            # When file is readonly there is no point in checking the pragma
            if [ -n "${readonly_condition}" ]; then
                has_pragma="true"
            else
                head=$(printf "%s" "${keyfile}" | head -n1)
                [ "${head}" = "${keyfile_head}" ] && has_pragma="true"
                # a firewall's file has no header: ssm leaves a marker
                if firewall_driver && plain_entry "$(login_home "${login}")/.ssh/${firewall_marker}"; then
                    has_pragma="true"
                fi
            fi

            readonly_scope=$(keyfile_condition_scope "${login}")
            readonly_ignored=""
            case "$(user_readonly_state "${login}")" in
                other) readonly_ignored="user_readonly not owned by root" ;;
                link) readonly_ignored="user_readonly is a link" ;;
                tampered) readonly_ignored="user_readonly unsafe (tampered?): ~/.ssh not root-owned or writable by others, or the marker is an ssm keyfile" ;;
            esac
            unsafe=$(keyfile_unsafe "${login}")
            [ -n "${unsafe}" ] || unsafe="${raced}"
            # sha256 of exactly what was read: a write can check it is unchanged
            sha=""
            [ -n "${unsafe}" ] || sha=$(printf "%s" "${keyfile}" | content_sha)

            printf '{"login":"%s", "has_pragma": %s, "readonly_condition": "%s", "readonly_scope": "%s", "readonly_ignored": "%s", "unsafe": "%s",' \
                "$(printf "%s" "${login}" | json_escape)" "${has_pragma}" \
                "$(printf "%s" "${readonly_condition}" | json_escape)" "${readonly_scope}" \
                "${readonly_ignored}" "${unsafe}"

            # every string field is JSON-escaped (json_escape)
            printf '"sha256":"%s",' "${sha}"
            printf '"keyfile":"%s"}' "$(printf "%s" "${keyfile}" | json_escape)"
      done
    printf "]"
}

# "yes" when anything sits at the login's ~/.ssh/authorized_keys (a link
# too, dangling or not) or its ~/.ssh is a link, else "no". "unknown" (exit
# 1) when getent does not know the login or its home does not exist: an
# LDAP outage or an unmounted home must not look like "no file". Nothing
# is read.
handle_has_keyfile() {
    home=$(login_home "$1") || home=""
    if [ -z "${home}" ] || { [ ! -e "${home}" ] && [ ! -h "${home}" ]; }; then
        echo "unknown"
        exit 1
    fi
    if [ -e "${home}/${authorized_keys_location}" ] \
        || [ -h "${home}/${authorized_keys_location}" ] || [ -h "${home}/.ssh" ]; then
        echo "yes"
    else
        echo "no"
    fi
    exit 0
}

handle_update() {
    newfile="${0}.new"
    cat - > "${newfile}"
    # Can we check if the new file is valid?
    mv "${newfile}" "${0}"
    exit 0
}

handle_version() {
    sha256=$(sha256sum "${0}" | awk '{ print $1 }')
    printf '{"version":"%s","sha256":"%s"}' "${version}" "${sha256}"
    exit 0
}

