defmodule SsmWeb.Mctl.People do
  @moduledoc """
  People of the mctl contract (section 10, capability `people`): what ssm
  knows about a person (`Ssm.People`) and offboarding.

  `remove/3` deletes the person's authorizations and runs a
  `remove_person` job that takes the person's public keys out of
  `authorized_keys` on the hosts (all hosts, or `params["hosts"]`): per
  login it reads the file, drops every line holding one of the keys and
  writes the rest back through `script.sh` (readonly markers are honoured,
  disabled hosts are never contacted). Only those lines change – a full
  sync would also push unrelated pending changes. Then the operator is
  disabled. Result `%{"hosts" => [%{"host_id", "ok", "error"}],
  "pending_keys" => [fingerprint], "kept_shared_keys" => [fingerprint]}`;
  hosts without any of the keys are left out.

  Key material never leaves ssm: the person is described by fingerprints.
  """

  alias MctlContract.Jobs.Ecto, as: Jobs
  alias Ssm.{Accounts, Activity, Hosts, People}
  alias Ssm.Hosts.Host
  alias Ssm.Ssh.ScriptRunner
  alias SsmWeb.Mctl.{Audit, HostParams}

  @task_supervisor Ssm.Mctl.TaskSupervisor
  @keyfile_head "# Auto-generated by Secure SSH Manager. DO NOT EDIT!"

  @doc "`{:ok, person}` (contract `Person`), `{:error, :not_found}` or a conflict."
  def get(key) do
    with {:ok, match} <- People.find(key), do: {:ok, render(match)}
  end

  @doc """
  `{:ok, job}`, `{:error, :not_found}`, a conflict (ambiguous `email:` key)
  or a validation error on `hosts`.

  Order (a failed host must leave something to retry): the authorizations
  of the person's own users go first (they are what a later sync would
  redeploy); the job then scrubs the key lines from the hosts; shared keys
  (other users' keys with the person's e-mail as comment) are deleted from
  the database only when every host was scrubbed – otherwise they stay and
  the job result lists them as `pending_keys`, and the next removal
  finishes them. With `hosts` only the person's own keys are scrubbed; the
  shared keys stay deployed and in the database and are reported as
  `kept_shared_keys` (a shared key cannot leave single hosts only).
  """
  def remove(principal, key, params) do
    with {:ok, match} <- People.find(key),
         {:ok, host_ids} <- host_ids(params["hosts"]) do
      plan = plan(match, host_ids)

      {:ok, touched} =
        People.remove_authorizations(match, host_ids, %{actor: Audit.actor(principal)})

      audit(principal, match, host_ids)
      work = &run(&1, match, plan, targets(host_ids, touched ++ plan.deployed))

      {:ok, job} = Jobs.run("remove_person", nil, work, task_supervisor: @task_supervisor)
      {:ok, Jobs.to_map(job)}
    end
  end

  # computed before the authorizations go: where the keys are meant to be
  defp plan(match, host_ids) do
    scrubbed = if host_ids, do: match.keys, else: People.all_keys(match)

    %{
      blobs: Enum.map(scrubbed, & &1.key_base64),
      deployed: Enum.flat_map(scrubbed, &People.key_hosts/1),
      shared: if(host_ids, do: [], else: match.shared_keys),
      kept: if(host_ids, do: match.shared_keys, else: [])
    }
  end

  defp host_ids(nil), do: {:ok, nil}

  defp host_ids(ids) do
    parsed = Enum.map(ids, &HostParams.parse_id/1)

    if Enum.all?(parsed, &match?({:ok, _}, &1)),
      do: {:ok, parsed |> Enum.map(fn {:ok, id} -> id end) |> Enum.uniq()},
      else: {:error, {:validation, %{"hosts" => ["must be host ids"]}}}
  end

  # every host (or the given ones); a disabled host is reported only when
  # it was asked for or the person's keys were meant to be there
  defp targets(nil, relevant) do
    Hosts.list_hosts() |> Enum.filter(&(not &1.disabled or &1.id in relevant))
  end

  defp targets(host_ids, _relevant), do: Enum.map(host_ids, &(Hosts.get_host(&1) || &1))

  defp run(job_id, match, plan, hosts) do
    {:ok, _} = Jobs.progress(job_id, "removing keys from #{length(hosts)} hosts")

    results =
      hosts
      |> Enum.map(&scrub(&1, plan.blobs))
      |> Enum.reject(&(&1 == :untouched))

    pending =
      if Enum.all?(results, & &1["ok"]) do
        People.delete_keys(Enum.map(plan.shared, & &1.id))
        []
      else
        plan.shared
      end

    _ = disable_operator(match.operator)

    {:ok,
     %{
       "hosts" => results,
       "pending_keys" => fingerprints(pending),
       "kept_shared_keys" => fingerprints(plan.kept)
     }}
  end

  defp fingerprints(keys), do: Enum.map(keys, &People.fingerprint(&1.key_base64))

  defp scrub(id, _blobs) when is_integer(id), do: result(id, {:error, "unknown host"})
  defp scrub(%Host{disabled: true} = host, _blobs), do: result(host.id, {:error, "host disabled"})
  defp scrub(%Host{} = _host, []), do: :untouched

  defp scrub(%Host{} = host, blobs) do
    target = Hosts.target_for(host)

    case ScriptRunner.get_ssh_keyfiles(Ssm.Ssh, target) do
      {:ok, entries} ->
        entries
        |> Enum.map(&scrub_login(target, &1, blobs))
        |> Enum.reject(&(&1 == :untouched))
        |> case do
          [] -> :untouched
          outcomes -> result(host.id, Enum.find(outcomes, :ok, &(&1 != :ok)))
        end

      {:error, reason} ->
        result(host.id, {:error, message(reason)})
    end
  end

  defp scrub_login(target, entry, blobs) do
    lines = entry.keyfile |> String.split("\n") |> Enum.reject(&(&1 == @keyfile_head))
    {drop, keep} = Enum.split_with(lines, &holds_key?(&1, blobs))

    cond do
      drop == [] ->
        :untouched

      entry.readonly_condition ->
        {:error, "#{entry.login}: readonly (#{entry.readonly_condition})"}

      true ->
        content = keep |> Enum.reject(&(&1 == "")) |> Enum.map_join("", &(&1 <> "\n"))

        case ScriptRunner.set_authorized_keyfile(Ssm.Ssh, target, entry.login, content) do
          :ok -> :ok
          {:error, reason} -> {:error, "#{entry.login}: #{message(reason)}"}
        end
    end
  end

  defp holds_key?(line, blobs) do
    line |> String.split(~r/\s+/, trim: true) |> Enum.any?(&(&1 in blobs))
  end

  defp result(host_id, :ok), do: %{"host_id" => to_string(host_id), "ok" => true, "error" => nil}

  defp result(host_id, {:error, message}),
    do: %{"host_id" => to_string(host_id), "ok" => false, "error" => message}

  defp message({_code, text}) when is_binary(text), do: text
  defp message(other), do: inspect(other)

  defp disable_operator(nil), do: :ok
  defp disable_operator(%{disabled_at: at}) when not is_nil(at), do: :ok
  defp disable_operator(operator), do: Accounts.set_disabled(operator, true)

  @doc "The contract `Person` of a match: fingerprints and comments only."
  def render(%People.Match{} = match) do
    %{
      key: match.key,
      operator: operator(match.operator),
      emails: List.wrap(match.email),
      keys:
        Enum.map(People.all_keys(match), fn k ->
          %{
            fingerprint: People.fingerprint(k.key_base64),
            comment: k.name,
            hosts: People.key_hosts(k),
            matched_by: People.key_reason(match, k)
          }
        end),
      authorizations:
        Enum.map(People.authorizations(match), fn a ->
          %{
            host_id: a.host_id,
            remote_user: a.login,
            matched_by: People.authorization_reason(match, a)
          }
        end)
    }
  end

  defp operator(nil), do: nil

  defp operator(op) do
    %{
      "id" => op.id,
      "name" => op.name,
      "email" => op.email,
      "verified_email" => op.verified_email,
      "role" => op.role,
      "disabled" => op.disabled_at != nil
    }
  end

  defp audit(principal, match, host_ids) do
    Activity.log(%{
      activity_type: "user",
      action: "mctl_remove_person",
      target: match.key,
      actor_username: Audit.actor(principal),
      details: %{
        via: "mctl",
        ip: principal.ip,
        hosts: host_ids || "all",
        keys: fingerprints(People.all_keys(match))
      }
    })
  end
end
