defmodule Ssm.Diffs.KeyRemoval do
  @moduledoc """
  "Remove key" / "Remove all extra keys" of the diff page: takes
  unauthorized (`:extra_on_host`) lines out of one login's
  `authorized_keys` without a full sync (which would also push unrelated
  pending changes), like `SsmWeb.Mctl.People` does for offboarding.

  The login is read fresh through `script.sh` and diffed again
  (`Ssm.Diffs.login_diff_for_write/2`): only lines that are still extra are
  removed — a key granted meanwhile, a present key, a granted key whose
  host line has other options, and ssm's own key never are. Every other line (comments included) is written back unchanged
  through `script.sh set_authorized_keyfile`, the one safe write path
  (handwritten files backed up, links replaced, never written through). A
  disabled host is refused before any SSH; a readonly login (host-wide
  marker or root-owned `user_readonly`) and an unsafe one (linked file or
  `~/.ssh`, not read) are refused before the write; the script's own
  refusals (shared home, …) are passed on. Like a sync, a login whose file
  holds ssm's own key is not written while that key is unavailable. The
  read and the write run under the host's write lock
  (`Ssm.Hosts.WriteLock`), and the write names the sha256 of the file as
  read, so a file changed on the host meanwhile is not overwritten
  (`:ssh_stale`).

  Every attempt is audit-logged (`activity_type` `host`, action
  `remove_keys` or `remove_keys_failed`) with the login, the number of
  lines and their key fingerprints — never the lines themselves. Who may
  call it (admins and in-scope operators, never viewers) is the caller's
  check.
  """

  alias Ssm.{Activity, Diffs, Hosts, People}
  alias Ssm.Hosts.{Host, WriteLock}
  alias Ssm.Ssh.ScriptRunner
  alias Ssm.Users.KeyParser

  @keyfile_head "# Auto-generated by Secure SSH Manager. DO NOT EDIT!"

  @type selector :: {:lines, [String.t()]} | :all_extra

  @doc """
  Remove the selected extra lines of `login` on `host` (`{:lines, lines}` —
  matched by key, as the diff compares them — or `:all_extra`). Returns
  `{:ok, %{removed: n}}` or `{:error, {tag, message}}` with tag
  `:host_disabled`, `:ssh_readonly`, `:ssh_unsafe`, `:stale` (nothing of
  the selection is extra on the host any more), `:own_key_unavailable` or
  `:ssh_connect_failed`.
  """
  @spec remove(module(), Host.t(), String.t(), selector(), String.t()) ::
          {:ok, %{removed: pos_integer()}} | {:error, {atom(), String.t()}}
  def remove(client \\ Ssm.Ssh, %Host{} = host, login, selector, actor) do
    host
    |> do_remove(client, login, selector)
    |> tap(&audit(&1, host, login, actor))
    |> case do
      {:ok, dropped} -> {:ok, %{removed: length(dropped)}}
      {:error, _} = error -> error
    end
  end

  defp do_remove(%Host{disabled: true} = host, _client, _login, _selector),
    do: {:error, {:host_disabled, "host #{inspect(host.name)} is disabled"}}

  # under the host's write lock (shared with sync and offboarding)
  defp do_remove(host, client, login, selector),
    do: WriteLock.run(host.id, fn -> locked_remove(host, client, login, selector) end)

  defp locked_remove(host, client, login, selector) do
    target = Hosts.target_for(host)

    with {:ok, entries} <- ScriptRunner.get_ssh_keyfiles(client, target),
         {:ok, entry} <- find_entry(entries, login, host),
         :ok <- ensure_writable(entry, host),
         {:ok, diff} <- Diffs.login_diff_for_write(host, entry),
         {:ok, drop_ids} <- selected_extras(diff, selector, host, login),
         {:ok, keep, dropped} <- split_file(entry.keyfile, drop_ids),
         :ok <-
           ScriptRunner.set_authorized_keyfile(client, target, login, content(keep),
             expected_sha256: entry.sha256
           ) do
      {:ok, dropped}
    end
  end

  defp find_entry(entries, login, host) do
    case Enum.find(entries, &(&1.login == login)) do
      nil ->
        {:error, {:stale, "#{inspect(login)} has no authorized_keys on #{inspect(host.name)}"}}

      entry ->
        {:ok, entry}
    end
  end

  defp ensure_writable(%{readonly_condition: condition} = entry, host)
       when is_binary(condition),
       do:
         {:error,
          {:ssh_readonly,
           "#{inspect(entry.login)} on #{inspect(host.name)} is readonly " <>
             "(#{condition |> String.slice(0, 200) |> inspect()}); nothing removed"}}

  defp ensure_writable(%{unsafe: unsafe} = entry, host) when is_binary(unsafe),
    do:
      {:error,
       {:ssh_unsafe,
        "#{inspect(entry.login)} on #{inspect(host.name)}: unsafe (#{unsafe}), not read; " <>
          "nothing removed"}}

  defp ensure_writable(_entry, _host), do: :ok

  # the key identities to drop: extras of the fresh diff, narrowed to the
  # selected lines. A granted key whose host line carries other options is
  # extra and missing at once: never dropped (the next sync fixes it).
  defp selected_extras(diff, selector, host, login) do
    granted =
      for %{status: status, line: line} <- diff.items,
          status != :extra_on_host,
          into: MapSet.new(),
          do: key_id(line)

    extras =
      for %{status: :extra_on_host, line: line} <- diff.items,
          not MapSet.member?(granted, key_id(line)),
          into: MapSet.new(),
          do: key_id(line)

    ids =
      case selector do
        :all_extra -> extras
        {:lines, lines} -> lines |> MapSet.new(&key_id/1) |> MapSet.intersection(extras)
      end

    if MapSet.size(ids) == 0,
      do:
        {:error,
         {:stale,
          "no unauthorized key of this selection left for #{inspect(login)} on " <>
            "#{inspect(host.name)}; refresh the diff"}},
      else: {:ok, ids}
  end

  # {:ok, lines kept (ssm's header dropped: the script writes it), lines dropped}
  defp split_file(keyfile, drop_ids) do
    lines =
      keyfile
      |> String.split("\n")
      |> Enum.map(&String.trim_trailing(&1, "\r"))
      |> Enum.reject(&(&1 == @keyfile_head or String.trim(&1) == ""))

    {dropped, keep} = Enum.split_with(lines, &drop?(&1, drop_ids))

    if dropped == [],
      do: {:error, {:stale, "the selected keys are no longer on the host; refresh the diff"}},
      else: {:ok, keep, dropped}
  end

  defp drop?(line, drop_ids) do
    trimmed = String.trim(line)
    not String.starts_with?(trimmed, "#") and MapSet.member?(drop_ids, key_id(trimmed))
  end

  defp key_id(line), do: KeyParser.identity(line) || {:line, String.trim(line)}

  defp content(lines), do: Enum.map_join(lines, "", &(&1 <> "\n"))

  defp audit(result, host, login, actor) do
    Activity.log(%{
      activity_type: "host",
      action: if(match?({:ok, _}, result), do: "remove_keys", else: "remove_keys_failed"),
      target: host.name,
      host_id: host.id,
      actor_username: actor,
      details: details(result, login)
    })
  end

  defp details({:ok, dropped}, login),
    do: %{login: login, removed: length(dropped), keys: Enum.map(dropped, &fingerprint/1)}

  defp details({:error, {_tag, message}}, login),
    do: %{login: login, removed: 0, error: String.slice(message, 0, 500)}

  defp fingerprint(line) do
    case KeyParser.identity(line) do
      {_type, base64} -> People.fingerprint(base64)
      nil -> "not a key line"
    end
  end
end
